//! Where a runner's files are in its folder, and the command lines Pitcrew starts it with.
//!
//! A runner Pitcrew installs keeps its binary in `<dir>/bin/`; a folder adopted from the PowerShell set-up has the
//! binary next to its `config.yaml` (`C:\gitea-runner\gitea-runner.exe`), which Pitcrew keeps using and updating in
//! place. The registration is `<dir>/.runner` (its existence is checked, its contents are never read), the runner's
//! own configuration `<dir>/config.yaml`, logs `<dir>/logs/runner.log`, job folders `<dir>/work` and the action
//! cache `<dir>/cache`.

use crate::config::RunnerConfig;
use crate::platform::Os;
use std::path::{Path, PathBuf};

/// The runner log's file name in `<dir>/logs`.
pub const LOG_FILE: &str = "runner.log";
/// The registration file's name (never read by Pitcrew).
pub const REGISTRATION_FILE: &str = ".runner";
/// The runner configuration's default file name.
pub const RUNNER_CONFIG: &str = "config.yaml";

/// The binary Pitcrew runs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RunnerBinary {
    /// Its path.
    pub path: PathBuf,
    /// Pitcrew may update it (false for a `binary_path` the user provides).
    pub managed: bool,
}

/// The binary of `runner`: the user's `binary_path`, else `<dir>/bin/<name>`, else `<dir>/<name>` when only that
/// exists (an adopted folder).
pub fn binary(runner: &RunnerConfig, os: Os, exists: impl Fn(&Path) -> bool) -> RunnerBinary {
    if let Some(p) = &runner.binary_path {
        return RunnerBinary {
            path: p.clone(),
            managed: false,
        };
    }
    let name = runner.kind.binary_file_name(os);
    let in_bin = runner.dir.join("bin").join(name);
    let legacy = runner.dir.join(name);
    let path = if !exists(&in_bin) && exists(&legacy) { legacy } else { in_bin };
    RunnerBinary { path, managed: true }
}

/// `<binary>.download`: where an update is downloaded (same folder, so the swap is a rename).
pub fn download_path(binary: &Path) -> PathBuf {
    with_suffix(binary, ".download")
}

/// `<binary>.previous`: the binary kept for roll-back.
pub fn previous_path(binary: &Path) -> PathBuf {
    with_suffix(binary, ".previous")
}

fn with_suffix(p: &Path, suffix: &str) -> PathBuf {
    let mut s = p.as_os_str().to_os_string();
    s.push(suffix);
    PathBuf::from(s)
}

/// The runner's own configuration file.
pub fn runner_config(runner: &RunnerConfig) -> PathBuf {
    runner.dir.join(runner.config_file.as_deref().unwrap_or(Path::new(RUNNER_CONFIG)))
}

/// The folder of its logs.
pub fn log_dir(runner: &RunnerConfig) -> PathBuf {
    runner.dir.join("logs")
}

/// Its registration file.
pub fn registration(runner: &RunnerConfig) -> PathBuf {
    runner.dir.join(REGISTRATION_FILE)
}

/// The folders housekeeping looks into: job work folders and the action cache.
pub fn work_dirs(runner: &RunnerConfig) -> (PathBuf, PathBuf) {
    (runner.dir.join("work"), runner.dir.join("cache"))
}

/// `daemon --config <config>`.
pub fn daemon_args(config: &Path) -> Vec<String> {
    vec!["daemon".into(), "--config".into(), config.display().to_string()]
}

/// The arguments of `register` (non-interactive). The token is passed to the runner only; callers must never log
/// these arguments.
pub fn register_args(config: &Path, server: &str, token: &str, name: &str, labels: &[String]) -> Vec<String> {
    let mut a: Vec<String> = vec![
        "--config".into(),
        config.display().to_string(),
        "register".into(),
        "--no-interactive".into(),
        "--instance".into(),
        server.into(),
        "--token".into(),
        token.into(),
        "--name".into(),
        name.into(),
    ];
    if !labels.is_empty() {
        a.push("--labels".into());
        a.push(labels.join(","));
    }
    a
}

/// A configuration generated by `generate-config`, with the job folders and the cache moved into the runner's
/// folder (where housekeeping finds them) instead of the account's home. Only the generated defaults are changed.
pub fn adjust_generated_config(text: &str, dir: &Path) -> String {
    let quote = |p: PathBuf| format!("'{}'", p.display().to_string().replace('\'', "''"));
    let mut section = String::new();
    // The generated `runner.timeout` (a job's longest run): a stop waits that long for a running job, not 0s.
    let mut job_timeout = String::from("3h");
    let mut out = String::with_capacity(text.len() + 128);
    for line in text.lines() {
        if !line.starts_with(' ') && !line.starts_with('#') && line.ends_with(':') {
            section = line.trim_end_matches(':').to_string();
        }
        let trimmed = line.trim();
        if section == "runner" {
            if let Some(v) = trimmed.strip_prefix("timeout:") {
                let v = v.split('#').next().unwrap_or("").trim();
                if !v.is_empty() {
                    job_timeout = v.to_string();
                }
            }
        }
        let replaced = match (section.as_str(), trimmed) {
            ("runner", t) if is_zero_shutdown_timeout(t) => Some(format!("  shutdown_timeout: {job_timeout}")),
            ("host", "workdir_parent:") | ("host", "workdir_parent: \"\"") => {
                Some(format!("  workdir_parent: {}", quote(dir.join("work"))))
            }
            ("cache", "dir: \"\"") | ("cache", "dir:") => Some(format!("  dir: {}", quote(dir.join("cache")))),
            _ => None,
        };
        out.push_str(replaced.as_deref().unwrap_or(line));
        out.push('\n');
    }
    out
}

/// `shutdown_timeout: 0s` (the generated default; also `0`): the runner cancels a running job the moment it is stopped.
fn is_zero_shutdown_timeout(trimmed: &str) -> bool {
    let Some(v) = trimmed.strip_prefix("shutdown_timeout:") else {
        return false;
    };
    matches!(v.split('#').next().unwrap_or("").trim(), "0" | "0s" | "\"0s\"" | "'0s'")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::SessionMode;
    use crate::distribution::RunnerKind;
    use crate::names::RunnerName;
    use crate::session::LoggedOffMode;

    fn runner(dir: &str) -> RunnerConfig {
        RunnerConfig {
            name: RunnerName::parse("a").unwrap(),
            kind: RunnerKind::GiteaRunner,
            dir: PathBuf::from(dir),
            config_file: None,
            labels: vec![],
            session: SessionMode::Interactive,
            logged_off: LoggedOffMode::Wait,
            server_url: None,
            enabled: true,
            binary_path: None,
            update: None,
            watchdog: None,
            cleanup: None,
            processes: None,
            env: Default::default(),
        }
    }

    #[test]
    fn binaries_live_in_bin_unless_the_folder_was_adopted() {
        let r = runner("/r/a");
        let b = binary(&r, Os::Macos, |_| false);
        assert_eq!(b.path, PathBuf::from("/r/a/bin/gitea-runner"));
        assert!(b.managed);
        let adopted = binary(&r, Os::Windows, |p| p == Path::new("/r/a").join("gitea-runner.exe"));
        assert_eq!(adopted.path, Path::new("/r/a").join("gitea-runner.exe"));
        let both = binary(&r, Os::Macos, |_| true);
        assert_eq!(both.path, PathBuf::from("/r/a/bin/gitea-runner"));
        let mut own = runner("/r/a");
        own.binary_path = Some(PathBuf::from("/opt/forgejo-runner"));
        assert!(!binary(&own, Os::Macos, |_| true).managed);
        assert_eq!(download_path(Path::new("/b/x.exe")), PathBuf::from("/b/x.exe.download"));
        assert_eq!(previous_path(Path::new("/b/x.exe")), PathBuf::from("/b/x.exe.previous"));
    }

    #[test]
    fn files_and_command_lines() {
        let mut r = runner("/r/a");
        assert_eq!(runner_config(&r), PathBuf::from("/r/a/config.yaml"));
        r.config_file = Some(PathBuf::from("other.yaml"));
        assert_eq!(runner_config(&r), PathBuf::from("/r/a/other.yaml"));
        assert_eq!(log_dir(&r), PathBuf::from("/r/a/logs"));
        assert_eq!(registration(&r), PathBuf::from("/r/a/.runner"));
        assert_eq!(work_dirs(&r).1, PathBuf::from("/r/a/cache"));
        assert_eq!(daemon_args(Path::new("/r/a/config.yaml"))[0], "daemon");
        let a = register_args(Path::new("c.yaml"), "https://g", "T", "n", &["x".into(), "y".into()]);
        assert_eq!(a.iter().position(|s| s == "--token").map(|i| a[i + 1].as_str()), Some("T"));
        assert_eq!(a.last().map(String::as_str), Some("x,y"));
        assert!(!register_args(Path::new("c"), "s", "t", "n", &[]).contains(&"--labels".to_string()));
    }

    #[test]
    fn a_stop_waits_for_a_running_job_as_long_as_a_job_may_run() {
        // The generated default `shutdown_timeout: 0s` cancels the running job on every stop (recorded 2026-10-28).
        let generated = "runner:\n  capacity: 1\n  timeout: 3h\n  shutdown_timeout: 0s\n  insecure: false\n";
        let out = adjust_generated_config(generated, Path::new("/r/a"));
        assert!(out.contains("  shutdown_timeout: 3h\n"), "{out}");
        assert!(!out.contains("0s"), "{out}");
        // It follows a non-default job timeout, and leaves a value somebody chose alone.
        let out = adjust_generated_config("runner:\n  timeout: 90m # longest job\n  shutdown_timeout: 0\n", Path::new("/r/a"));
        assert!(out.contains("  shutdown_timeout: 90m\n"), "{out}");
        let chosen = "runner:\n  timeout: 3h\n  shutdown_timeout: 30s\n";
        assert_eq!(adjust_generated_config(chosen, Path::new("/r/a")), chosen);
        // Another section's key of that name is not ours.
        let other = "other:\n  shutdown_timeout: 0s\n";
        assert_eq!(adjust_generated_config(other, Path::new("/r/a")), other);
    }

    #[test]
    fn generated_configs_keep_jobs_and_cache_in_the_runner_folder() {
        let generated =
            "log:\n  level: info\ncache:\n  enabled: true\n  dir: \"\"\nhost:\n  # parent\n  workdir_parent:\nother:\n  dir: \"\"\n";
        let dir = Path::new("/r/o'k");
        let out = adjust_generated_config(generated, dir);
        let quoted = |p: PathBuf| format!("'{}'", p.display().to_string().replace('\x27', "''"));
        assert!(out.contains(&format!("  workdir_parent: {}", quoted(dir.join("work")))), "{out}");
        assert!(out.contains(&format!("  dir: {}", quoted(dir.join("cache")))), "{out}");
        assert!(out.contains("o''k"), "quotes are doubled: {out}");
        assert!(out.ends_with("other:\n  dir: \"\"\n"), "other sections are untouched: {out}");
        let custom = "host:\n  workdir_parent: D:\\jobs\n";
        assert_eq!(adjust_generated_config(custom, Path::new("/r")), custom);
    }
}
