#!/usr/bin/env node
// Builds the offline world map of the connections map (ADR 0031 section 3.3, D6) from Natural Earth 1:110m Admin 0 countries
// (public domain, https://www.naturalearthdata.com/about/terms-of-use/): Equal Earth projected, integer coordinates, one path per
// country keyed by ISO_A2_EH (ISO_A2 is -99 for France and Norway), plus a centroid per country.
//
//   node scripts/build-world-map.mjs <ne_110m_admin_0_countries.geojson> [out.ts]
//
// The output carries the SHA-256 of the source file. Run it again only when the source changes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [src, out = new URL('../app/src/app/features/map/world-map.data.ts', import.meta.url).pathname] = process.argv.slice(2);
if (!src) {
  console.error('usage: build-world-map.mjs <ne_110m_admin_0_countries.geojson> [out.ts]');
  process.exit(2);
}
const bytes = readFileSync(src);
const sha = createHash('sha256').update(bytes).digest('hex');
const geo = JSON.parse(bytes.toString('utf8'));

const W = 1000;
// The map is projected at run time (Equal Earth, centred on the user's longitude: map-geometry.ts), so the output keeps longitude
// and latitude in tenths of a degree: each ring is "lon lat" then steps from the previous point, rings joined by "|".
const H = Math.ceil(2 * 1.3173 * (W / (2 * ((2 * Math.sqrt(3) * Math.PI) / (3 * 1.340264))))) + 4;

function ringPath(ring) {
  const pts = [];
  for (const [lon, lat] of ring) {
    const p = [Math.round(lon * 10), Math.round(lat * 10)];
    const last = pts[pts.length - 1];
    if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
  }
  if (pts.length < 4) return '';
  const out = [`${pts[0][0]} ${pts[0][1]}`];
  for (let i = 1; i < pts.length; i++) out.push(`${pts[i][0] - pts[i - 1][0]} ${pts[i][1] - pts[i - 1][1]}`);
  return out.join(' ');
}

function area(ring) {
  let a = 0;
  for (let i = 0; i < ring.length - 1; i++) a += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  return a / 2;
}
function centroid(ring) {
  let a = 0, cx = 0, cy = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const f = ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
    a += f;
    cx += (ring[i][0] + ring[i + 1][0]) * f;
    cy += (ring[i][1] + ring[i + 1][1]) * f;
  }
  return a === 0 ? ring[0] : [cx / (3 * a), cy / (3 * a)];
}

const shapes = {};
const centres = {};
for (const f of geo.features) {
  const code = f.properties.ISO_A2_EH && f.properties.ISO_A2_EH !== '-99' ? f.properties.ISO_A2_EH : f.properties.ISO_A2;
  if (!code || code === '-99') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = polys.map((p) => p[0]);
  const d = rings.map(ringPath).filter(Boolean).join('|');
  if (!d) continue;
  shapes[code] = shapes[code] ? `${shapes[code]}|${d}` : d;
  const biggest = rings.reduce((b, r) => (Math.abs(area(r)) > Math.abs(area(b)) ? r : b));
  const [lon, lat] = centroid(biggest);
  centres[code] = [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10];
}
const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const body = `// Generated by scripts/build-world-map.mjs from Natural Earth 1:110m Admin 0 countries (public domain; credit not required).
// Source SHA-256: ${sha}
// Longitude and latitude in tenths of a degree; projected at run time by map-geometry.ts. Do not edit by hand.

/** The viewBox of the map. */
export const MAP_VIEW = { width: ${W}, height: ${H} } as const;

/** Source file hash. */
export const MAP_SOURCE_SHA256 = '${sha}';

/** Outlines per country, keyed by ISO 3166-1 alpha-2 (\`ISO_A2_EH\`): rings joined by "|", each "lon lat" then steps, in tenths of a degree. */
export const COUNTRY_RINGS: Readonly<Record<string, string>> = ${JSON.stringify(sorted(shapes))};

/** Centre of each drawn country as [longitude, latitude]. */
export const COUNTRY_CENTRES: Readonly<Record<string, readonly [number, number]>> = ${JSON.stringify(sorted(centres))};
`;
writeFileSync(out, body);
console.log(`${Object.keys(shapes).length} countries, ${(body.length / 1024).toFixed(0)} KB, viewBox ${W}x${H}`);
