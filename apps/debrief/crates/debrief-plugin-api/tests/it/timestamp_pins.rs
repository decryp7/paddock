#[test]
fn user_formats_read_as_before() {
    assert!(FORMATS.len() > 300, "the table is not empty");
    let mut wrong = Vec::new();
    for &(zone, fmt, input, want) in FORMATS {
        let p = TimestampParser::new(&[fmt.to_string()], zone, None)
            .unwrap()
            .with_reference(Some(REFERENCE_MS));
        let got = p.parse(input);
        if got != want {
            wrong.push(format!("{zone} {fmt:?} {input:?}: want {want:?}, got {got:?}"));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} differ:\n{}",
        wrong.len(),
        FORMATS.len(),
        wrong.join("\n")
    );
}

