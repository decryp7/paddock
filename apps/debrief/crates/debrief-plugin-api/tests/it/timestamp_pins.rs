/// Positive control: the comparison sees a wrong expectation.
#[test]
fn the_table_detects_a_changed_value() {
    let p = TimestampParser::new(&["%Y-%m-%d %H:%M:%S".to_string()], Z_UTC, None).unwrap();
    assert_ne!(p.parse("2026-10-14 10:41:22"), Some(1_791_974_482_001));
    assert_eq!(p.parse("2026-10-14 10:41:22"), Some(1_791_974_482_000));
}
