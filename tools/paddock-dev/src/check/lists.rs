//! `./dev check lists`: the lists that name the Rust host's checks, written from the checks themselves (user decision, 2026-11-28, in
//! chat; ER-40, ER-22, ER-42). A check declares itself once, in its `impl Check` in `src/check/c<n>.rs` (id, title, scope, mode, needs,
//! origin); nothing else is kept by hand. What is generated from those declarations:
//!
//! - the registry and the module lines of `src/check/mod.rs` and the test module lines of `tests/it/main.rs`: written by `build.rs` into
//!   `OUT_DIR` from the file names, so no committed text exists to conflict on or to go stale;
//! - `conformance.rust` of `conformance/paddock.ci.json`: the registry's checks that have no JavaScript module (the checks only this host
//!   runs), in id order; [`contract_text`];
//! - the table of Rust checks in `conformance/README.md`, between [`README_BEGIN`] and [`README_END`]; [`readme_text`].
//!
//! `./dev check lists` rewrites the two committed lists and prints what changed; `--check` changes nothing and exits 1 with the
//! difference when one is stale (`./dev gen check`, entry `rust-check-lists` of docs/generators.toml). The JavaScript host's own lists
//! (`conformance.only`, the JavaScript table) stay with `conformance/bin/paddock-check-lists.mjs`; the two generators write different
//! keys and markers of the same files. `docs/gates.toml` stays by hand: it holds approvals, not a list of what exists.
//!
//! The contract is read and written through its JSON parser (`serde_json`, key order kept), never by editing text (ER-42).

use super::{Check, CheckScope};
use paddock_cli::{CliError, Exit, Report};
use serde_json::{Value, json};
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::time::Instant;

/// The CI contract that holds `conformance.rust`.
pub const CONTRACT: &str = "conformance/paddock.ci.json";
/// The README that holds the table of Rust checks.
pub const README: &str = "conformance/README.md";
/// The folder of the JavaScript check modules (`C<n>-<slug>.mjs`).
pub const JS_CHECKS: &str = "conformance/src/checks";
/// The line that starts the table of Rust checks in the README.
pub const README_BEGIN: &str =
    "<!-- rust-checks:begin (generated by ./dev check lists from each Rust check's `impl Check`; do not edit) -->";
/// The line that ends it.
pub const README_END: &str = "<!-- rust-checks:end -->";
/// The command that regenerates both lists, as an error shows it.
pub const REGENERATE: &str = "./dev check lists";

/// The ids of the JavaScript check modules: the file names `C<n>-*.mjs` of [`JS_CHECKS`] (names only; `index.mjs` and other files are
/// not modules). Sorted.
pub fn js_module_ids(root: &Path) -> Result<BTreeSet<String>, String> {
    let dir = root.join(JS_CHECKS);
    let rd = std::fs::read_dir(&dir).map_err(|e| format!("cannot read {JS_CHECKS}: {e}"))?;
    let mut out = BTreeSet::new();
    for entry in rd.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let Some(stem) = name.strip_suffix(".mjs") else { continue };
        let id = stem.split('-').next().unwrap_or("");
        if id.len() > 1 && id.starts_with('C') && id[1..].bytes().all(|b| b.is_ascii_digit()) {
            out.insert(id.to_string());
        }
    }
    Ok(out)
}

/// The numeric part of a check id (`C183` is 183), for id order.
fn number(id: &str) -> u32 {
    id.strip_prefix('C').and_then(|n| n.parse().ok()).unwrap_or(u32::MAX)
}

/// The registry's checks that no JavaScript module has: the ones only this host runs, in id order.
pub fn rust_only<'a>(registry: &'a [Box<dyn Check>], js: &BTreeSet<String>) -> Vec<&'a dyn Check> {
    let mut mine: Vec<&dyn Check> = registry.iter().map(|c| c.as_ref()).filter(|c| !js.contains(c.id())).collect();
    mine.sort_by_key(|c| number(c.id()));
    mine
}

/// `text` (the CI contract) with `conformance.rust` set to `ids`; every other key and its order stay. An error names what is wrong with
/// the file.
pub fn contract_text(text: &str, ids: &[&str]) -> Result<String, String> {
    let mut json: Value = serde_json::from_str(text).map_err(|e| format!("{CONTRACT} is not JSON: {e}"))?;
    let conformance = json
        .get_mut("conformance")
        .and_then(Value::as_object_mut)
        .ok_or_else(|| format!("{CONTRACT} has no `conformance` object"))?;
    conformance.insert("rust".to_string(), json!(ids));
    let mut out = serde_json::to_string_pretty(&json).map_err(|e| e.to_string())?;
    out.push('\n');
    Ok(out)
}

/// A table cell: one line, `|` escaped.
fn cell(v: &str) -> String {
    v.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|")
}

fn scope_name(s: CheckScope) -> &'static str {
    match s {
        CheckScope::Root => "root",
        CheckScope::Apps => "apps",
        CheckScope::Both => "both",
    }
}

/// `text` (the README) with the table between [`README_BEGIN`] and [`README_END`] written from `checks`. An error when the markers are
/// missing or out of order.
pub fn readme_text(text: &str, checks: &[&dyn Check]) -> Result<String, String> {
    let begin = text.find(README_BEGIN);
    let end = text.find(README_END);
    let (Some(begin), Some(end)) = (begin, end) else {
        return Err(format!(
            "{README} needs the lines {README_BEGIN} and {README_END}, in that order, around the table of Rust checks"
        ));
    };
    if end < begin {
        return Err(format!("{README}: the line {README_END} comes before {README_BEGIN}"));
    }
    let mut rows = vec![
        "| Id | Title | Scope | Mode | Needs | Origin |".to_string(),
        "|---|---|---|---|---|---|".to_string(),
    ];
    for c in checks {
        rows.push(format!(
            "| {} | {} | {} | {} | {} | {} |",
            cell(c.id()),
            cell(c.title()),
            scope_name(c.scope()),
            c.mode().name(),
            c.needs().name(),
            c.origin().name()
        ));
    }
    let mut out = String::with_capacity(text.len());
    out.push_str(&text[..begin]);
    out.push_str(README_BEGIN);
    out.push('\n');
    out.push_str(&rows.join("\n"));
    out.push('\n');
    out.push_str(&text[end..]);
    Ok(out)
}

/// What is written where: `(path, new text)` for each list, from the registry and the files at `root`.
pub fn generate(root: &Path, registry: &[Box<dyn Check>]) -> Result<Vec<(&'static str, String)>, String> {
    let js = js_module_ids(root)?;
    let mine = rust_only(registry, &js);
    let ids: Vec<&str> = mine.iter().map(|c| c.id()).collect();
    let read = |p: &str| std::fs::read_to_string(root.join(p)).map_err(|e| format!("cannot read {p}: {e}"));
    Ok(vec![
        (CONTRACT, contract_text(&read(CONTRACT)?, &ids)?),
        (README, readme_text(&read(README)?, &mine)?),
    ])
}

/// The lines that differ between `have` and `want`, as `- old` and `+ new` (by line, not by position), at most 12.
pub fn line_diff(have: &str, want: &str) -> Vec<String> {
    let h: BTreeSet<&str> = have.lines().collect();
    let w: BTreeSet<&str> = want.lines().collect();
    let mut out: Vec<String> = have.lines().filter(|l| !w.contains(l)).map(|l| format!("- {l}")).collect();
    out.extend(want.lines().filter(|l| !h.contains(l)).map(|l| format!("+ {l}")));
    out.truncate(12);
    out
}

/// `./dev check lists [--check]`.
pub fn command(root: Option<PathBuf>, check: bool) -> Result<Report, CliError> {
    let root = crate::repo_root::repo_root(root.as_deref())?;
    if !check && std::env::var("CI").is_ok_and(|v| v == "true") {
        return Err(
            CliError::refused("::error::check lists: CI=true: CI checks the lists (--check) and never rewrites them.")
                .with_hint(format!("Run `{REGENERATE}` on your machine and commit the result.")),
        );
    }
    let started = Instant::now();
    let registry = super::registry();
    let out = generate(&root, &registry).map_err(|e| {
        CliError::failure(format!("::error::check lists: {e}.")).with_hint("Fix what it names, then run `./dev check lists` again.")
    })?;
    let mut stale = Vec::new();
    let mut lines = String::new();
    for (path, want) in &out {
        let have = std::fs::read_to_string(root.join(path)).unwrap_or_default();
        if have == *want {
            continue;
        }
        stale.push(*path);
        if check {
            lines.push_str(&format!(
                "::error file={path}::{path} is stale: run `{REGENERATE}` and commit the result\n"
            ));
        } else {
            std::fs::write(root.join(path), want)
                .map_err(|e| CliError::failure(format!("::error::check lists: cannot write {path}: {e}.")))?;
            lines.push_str(&format!("wrote {path}\n"));
        }
        for l in line_diff(&have, want) {
            lines.push_str(&format!("  {l}\n"));
        }
    }
    let ms = started.elapsed().as_millis();
    if check && !stale.is_empty() {
        return Err(CliError::new(Exit::Findings, lines.trim_end().to_string()).with_hint(format!(
            "Run `{REGENERATE}` and commit what it rewrites (ER-40: generated lists are never edited by hand)."
        )));
    }
    let total = registry.len();
    if stale.is_empty() {
        lines.push_str(&format!("check lists: current ({total} checks in the registry, {ms} ms)\n"));
    }
    Ok(Report::new(
        json!({"stale": stale, "checks": total, "ms": ms}),
        lines.trim_end().to_string(),
    ))
}
