//! The notices document: a pure function of the packages, deterministic (sorted, no paths, no dates), so CI can compare it.
//! Ports `render` of `generate.mjs`; the golden files under `tests/golden/notices/` are what that function wrote.

use super::sources::{Kind, Package};
use super::text::{cmp16, len16};
use sha2::{Digest, Sha256};
use std::collections::HashMap;

/// What was counted while rendering.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Counts {
    /// Rust crates listed.
    pub rust: usize,
    /// npm packages listed.
    pub npm: usize,
    /// Distinct licence texts.
    pub texts: usize,
    /// Distinct licence expressions.
    pub expressions: usize,
}

/// The document and its counts.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    /// The Markdown, LF line endings, ending in one newline.
    pub markdown: String,
    /// The counts.
    pub counts: Counts,
}

struct TextRec {
    text: String,
    id: String,
    users: Vec<String>,
    label: String,
}

/// Wraps `items` joined by ", " at `width` UTF-16 units (a line is never empty; an over-long item gets its own line).
fn wrap(items: &[String], width: usize) -> Vec<String> {
    let mut lines = Vec::new();
    let mut cur = String::new();
    for it in items {
        let next = if cur.is_empty() { it.clone() } else { format!("{cur}, {it}") };
        if len16(&next) > width && !cur.is_empty() {
            lines.push(format!("{cur},"));
            cur = it.clone();
        } else {
            cur = next;
        }
    }
    if !cur.is_empty() {
        lines.push(cur);
    }
    lines
}

fn sha256_hex(text: &str) -> String {
    Sha256::digest(text.as_bytes()).iter().map(|b| format!("{b:02x}")).collect()
}

/// The notices document; `app_name` is the product name in the intro.
pub fn render(rust: &[Package], npm: &[Package], app_name: &str) -> Rendered {
    let mut all: Vec<&Package> = rust.iter().chain(npm).collect();
    all.sort_by(|a, b| {
        a.kind
            .cmp(&b.kind)
            .then_with(|| cmp16(&a.name, &b.name))
            .then_with(|| cmp16(&a.version, &b.version))
    });

    let mut by_hash: HashMap<String, usize> = HashMap::new();
    let mut recs: Vec<(String, TextRec)> = Vec::new();
    let mut refs: Vec<Vec<usize>> = Vec::with_capacity(all.len());
    for p in &all {
        let mut mine = Vec::new();
        for t in &p.texts {
            let h = sha256_hex(&t.text);
            let i = *by_hash.entry(h.clone()).or_insert_with(|| {
                let id =
                    t.id.clone()
                        .or_else(|| p.spdx.first().cloned())
                        .unwrap_or_else(|| p.license.clone());
                recs.push((
                    h,
                    TextRec {
                        text: t.text.clone(),
                        id,
                        users: vec![],
                        label: String::new(),
                    },
                ));
                recs.len() - 1
            });
            recs[i].1.users.push(format!("{} {}", p.name, p.version));
            mine.push(i);
        }
        refs.push(mine);
    }
    let mut order: Vec<usize> = (0..recs.len()).collect();
    order.sort_by(|&a, &b| cmp16(&recs[a].1.id, &recs[b].1.id).then_with(|| recs[a].0.cmp(&recs[b].0)));
    let mut counters: HashMap<String, usize> = HashMap::new();
    for &i in &order {
        let n = counters.entry(recs[i].1.id.clone()).or_insert(0);
        *n += 1;
        recs[i].1.label = format!("{}-{n}", recs[i].1.id);
    }
    let mut tally: Vec<(&str, usize)> = Vec::new();
    for p in &all {
        match tally.iter_mut().find(|(l, _)| *l == p.license) {
            Some((_, n)) => *n += 1,
            None => tally.push((&p.license, 1)),
        }
    }

    let mut out: Vec<String> = vec!["# Third-party notices".into(), String::new()];
    out.push(format!(
        "{app_name} is dual-licensed MIT OR Apache-2.0 (see LICENSE-MIT and LICENSE-APACHE). It includes the third-party software listed below,"
    ));
    out.push("each under its own licence. This file is generated by paddock-notices; do not edit it by hand.".into());
    out.push(String::new());
    out.extend([
        "## Summary".into(),
        String::new(),
        format!("- Rust crates: {}", rust.len()),
        format!("- npm packages: {}", npm.len()),
    ]);
    out.push(format!("- Distinct licence texts: {}", recs.len()));
    out.extend([String::new(), "Licence expressions (packages):".into(), String::new()]);
    let mut by_count = tally.clone();
    by_count.sort_by(|(a, x), (b, y)| y.cmp(x).then_with(|| cmp16(a, b)));
    out.extend(by_count.iter().map(|(lic, n)| format!("- {lic}: {n}")));
    for (heading, kind) in [("Rust crates", Kind::Rust), ("npm packages", Kind::Npm)] {
        let list: Vec<usize> = (0..all.len()).filter(|&i| all[i].kind == kind).collect();
        out.extend([String::new(), format!("## {heading} ({})", list.len()), String::new()]);
        for i in list {
            let mut labels: Vec<&str> = Vec::new();
            for &r in &refs[i] {
                if !labels.contains(&recs[r].1.label.as_str()) {
                    labels.push(&recs[r].1.label);
                }
            }
            let shown = if labels.is_empty() {
                "no text".to_string()
            } else {
                labels.join(", ")
            };
            out.push(format!("- {} {} — {} [{shown}]", all[i].name, all[i].version, all[i].license));
        }
    }
    out.extend([String::new(), "## Licence texts".into(), String::new()]);
    for &i in &order {
        let t = &recs[i].1;
        let mut users: Vec<String> = t.users.clone();
        users.sort_by(|a, b| cmp16(a, b));
        users.dedup();
        out.extend([format!("### {}", t.label), String::new(), format!("Used by ({}):", users.len())]);
        out.extend(wrap(&users, 96).into_iter().map(|l| format!("  {l}")));
        out.push(String::new());
        out.extend(
            t.text
                .split('\n')
                .map(|l| if l.is_empty() { String::new() } else { format!("    {l}") }),
        );
        out.push(String::new());
    }
    let joined = out.join("\n");
    Rendered {
        markdown: format!("{}\n", joined.trim_end_matches('\n')),
        counts: Counts {
            rust: rust.len(),
            npm: npm.len(),
            texts: recs.len(),
            expressions: tally.len(),
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::notices::sources::Text;
    use crate::notices::text::spdx_ids;

    fn pkg(kind: Kind, name: &str, license: &str, texts: &[(Option<&str>, &str)]) -> Package {
        Package {
            kind,
            name: name.into(),
            version: "1.0.0".into(),
            license: license.into(),
            texts: texts
                .iter()
                .map(|(id, t)| Text {
                    id: id.map(String::from),
                    text: (*t).into(),
                })
                .collect(),
            spdx: spdx_ids(license),
        }
    }

    #[test]
    fn the_output_does_not_depend_on_the_input_order_and_texts_are_shared() {
        let a = pkg(Kind::Rust, "zeta", "MIT", &[(Some("MIT"), "MIT text")]);
        let b = pkg(Kind::Rust, "alpha", "MIT", &[(Some("MIT"), "MIT text")]);
        let c = pkg(Kind::Npm, "pad", "Apache-2.0", &[(None, "other")]);
        let one = render(&[a.clone(), b.clone()], std::slice::from_ref(&c), "Demo");
        let two = render(&[b, a], &[c], "Demo");
        assert_eq!(one, two);
        assert_eq!(
            one.counts,
            Counts {
                rust: 2,
                npm: 1,
                texts: 2,
                expressions: 2
            }
        );
        assert!(
            one.markdown
                .starts_with("# Third-party notices\n\nDemo is dual-licensed MIT OR Apache-2.0")
        );
        assert!(one.markdown.contains("Used by (2):\n  alpha 1.0.0, zeta 1.0.0\n"));
        assert!(one.markdown.contains("- pad 1.0.0 — Apache-2.0 [Apache-2.0-1]"), "{}", one.markdown);
        assert!(one.markdown.ends_with("    MIT text\n") && !one.markdown.contains('\r'));
    }

    #[test]
    fn a_package_without_text_says_so_and_an_empty_set_still_renders() {
        let r = render(&[pkg(Kind::Rust, "bare", "ISC", &[])], &[], "X");
        assert!(r.markdown.contains("- bare 1.0.0 — ISC [no text]"));
        let empty = render(&[], &[], "X");
        assert!(
            empty
                .markdown
                .contains("## Rust crates (0)\n\n\n## npm packages (0)\n\n\n## Licence texts\n")
        );
        assert!(empty.markdown.ends_with("## Licence texts\n"));
    }

    #[test]
    fn long_user_lists_wrap_at_96_units_and_blank_text_lines_stay_blank() {
        let users: Vec<String> = (0..30).map(|i| format!("crate-number-{i:02} 1.0.0")).collect();
        let lines = wrap(&users, 96);
        assert!(lines.len() > 1 && lines.iter().all(|l| len16(l) <= 97 && !l.is_empty()));
        assert!(lines[0].ends_with(','));
        let r = render(&[pkg(Kind::Rust, "a", "MIT", &[(Some("MIT"), "one\n\ntwo")])], &[], "X");
        assert!(r.markdown.contains("    one\n\n    two\n"));
    }
}
