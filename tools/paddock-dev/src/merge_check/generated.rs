//! Files that are regenerated, not merged: every detector skips them (one list, so the three cannot disagree). A file is
//! generated when its name is on the list below or the repository marks it `linguist-generated` in `.gitattributes`.

use super::git::Git;
use std::collections::HashSet;

/// Whether the name alone says "regenerated": lock files (`Cargo.lock` among them, by the `.lock` suffix), the notices file, drawio sources and generated Rust.
pub fn by_name(path: &str) -> bool {
    let name = path.rsplit('/').next().unwrap_or(path);
    name == "THIRD_PARTY_NOTICES.md"
        || name == "package-lock.json"
        || name.ends_with(".lock")
        || name.ends_with(".drawio")
        || path.contains("permissions/autogenerated")
        || path.ends_with("widgets/generated.rs")
}

/// The generated files among the paths a check looks at.
#[derive(Default)]
pub struct Generated {
    marked: HashSet<String>,
}

impl Generated {
    /// Reads the `linguist-generated` attribute of `paths` at `tree` (`git check-attr --source`, in chunks).
    pub fn load(git: &Git, tree: &str, paths: &[String]) -> Result<Generated, String> {
        let mut marked = HashSet::new();
        for chunk in paths.chunks(200) {
            let mut args = vec!["check-attr", "-z", "--source", tree, "linguist-generated", "--"];
            args.extend(chunk.iter().map(String::as_str));
            marked.extend(parse_attr(&git.text(&args)?));
        }
        Ok(Generated { marked })
    }

    /// Whether `path` is generated.
    pub fn is(&self, path: &str) -> bool {
        by_name(path) || self.marked.contains(path)
    }
}

/// The paths a `check-attr -z` listing (`path NUL attribute NUL value NUL ...`) marks as set.
fn parse_attr(out: &str) -> Vec<String> {
    let parts: Vec<&str> = out.split('\0').collect();
    parts
        .chunks(3)
        .filter(|c| c.len() == 3 && matches!(c[2], "set" | "true"))
        .map(|c| c[0].to_string())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_names_that_are_regenerated() {
        for p in [
            "Cargo.lock",
            "apps/x/Cargo.lock",
            "package-lock.json",
            "yarn.lock",
            "THIRD_PARTY_NOTICES.md",
            "docs/a.drawio",
            "crates/p/permissions/autogenerated/x.toml",
            "ui/widgets/generated.rs",
        ] {
            assert!(by_name(p), "{p}");
        }
        assert!(!by_name("src/lib.rs") && !by_name("docs/notices.md") && !by_name("widgets/generated_by_hand.rs"));
    }

    #[test]
    fn attribute_output_is_read_three_fields_at_a_time() {
        let out = "a.gen.txt\0linguist-generated\0set\0b.rs\0linguist-generated\0unspecified\0";
        assert_eq!(parse_attr(out), vec!["a.gen.txt"]);
    }
}
