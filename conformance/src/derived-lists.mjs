// The lists that name every conformance check, derived from the check modules (ER-40, ER-42): the modules in
// conformance/src/checks (`C<n>-<slug>.mjs`, each exporting its id, title, scope, mode and needs) are the one registry. From
// them this module derives
//
//   - conformance/src/checks/index.mjs: one import per module and the `checks` list, in id order;
//   - `conformance.only` of conformance/paddock.ci.json: every check, in id order, except the ones `conformance.skip` names
//     with the reason Paddock does not run them on its own tree;
//   - the check index of conformance/README.md, between its two `checks:` markers: id, title, scope, mode and needs.
//
// Adding a check is: write the module (its id from `./dev check new-id --reserve <branch>`), then run
// `node conformance/bin/paddock-check-lists.mjs`. `--check` (the generator registry's `conformance-check-lists` entry and
// test/check-lists.test.mjs) fails when a list is stale and prints that command. Everything here is pure over texts;
// bin/paddock-check-lists.mjs does the reading and writing.

/** A check module's file name: `C<n>-<slug>.mjs`. */
export const MODULE = /^C(\d+)-[a-z0-9][a-z0-9-]*\.mjs$/;

/** The command that rewrites the lists, as the errors print it. */
export const REGENERATE = 'node conformance/bin/paddock-check-lists.mjs';

/** The repository paths of the generated lists. */
export const INDEX_PATH = 'conformance/src/checks/index.mjs';
export const CONTRACT_PATH = 'conformance/paddock.ci.json';
export const README_PATH = 'conformance/README.md';

/** The markers around the generated check index in the README. */
export const README_BEGIN = `<!-- checks:begin (generated by ${REGENERATE} from the check modules; do not edit) -->`;
export const README_END = '<!-- checks:end -->';

/**
 * The check modules among `files` (the file names in conformance/src/checks, folders left out), in id order:
 * `[{ id, n, file }]`. Every file but index.mjs and dotfiles must be a module: a misnamed one (`C127_foo.mjs`, `c127-foo.mjs`,
 * `C127-foo.js`, `C127.mjs`) would otherwise never be imported, so its check would never run. Throws on that and on two
 * modules with one id, so a clash between branches fails at the regenerate, not at run time.
 */
export function modules(files) {
  const out = [];
  const seen = new Map();
  for (const file of files) {
    if (file === 'index.mjs' || file.startsWith('.')) continue; // dotfiles (.DS_Store from Finder) are no modules
    const m = MODULE.exec(file);
    if (!m) {
      throw new Error(
        `conformance/src/checks/${file} is not a check module: name it C<n>-<slug>.mjs (a capital C, the number, a dash, a lower-case slug of letters, digits and dashes, .mjs), or move a helper to conformance/src/checks/lib/`,
      );
    }
    const id = `C${m[1]}`;
    if (seen.has(id)) throw new Error(`check id ${id} has two modules (${seen.get(id)} and ${file}): renumber one with \`./dev check new-id --reserve <branch>\``);
    seen.set(id, file);
    out.push({ id, n: Number(m[1]), file });
  }
  return out.sort((a, b) => a.n - b.n);
}

/** The text of conformance/src/checks/index.mjs for these modules. */
export function indexText(mods) {
  const lines = [
    `// Generated by ${REGENERATE} from the check modules in this folder. Do not edit:`,
    '// add a check by writing its module (C<n>-<slug>.mjs), then run the command.',
    ...mods.map((m) => `import ${m.id} from './${m.file}';`),
    '',
    '/** Every check, in id order. A check is { id, title, rule, run(ctx) -> findings[] | Promise<findings[]> }. */',
    `export const checks = [${mods.map((m) => m.id).join(', ')}];`,
    '',
  ];
  return lines.join('\n');
}

/**
 * conformance/paddock.ci.json with `conformance.only` rewritten: every module's id in id order, less `conformance.skip`'s keys.
 * Throws when `skip` is missing, names a check that has no module, or gives no reason, and when `strict` names a check that
 * does not run.
 */
export function contractText(text, mods) {
  const json = JSON.parse(text);
  const c = json.conformance;
  if (!c || typeof c !== 'object') throw new Error(`${CONTRACT_PATH} has no \`conformance\` object`);
  const skip = c.skip;
  if (!skip || typeof skip !== 'object' || Array.isArray(skip)) {
    throw new Error(`${CONTRACT_PATH}: \`conformance.skip\` must be an object of check id to the reason Paddock does not run it`);
  }
  const ids = new Set(mods.map((m) => m.id));
  for (const [id, why] of Object.entries(skip)) {
    if (!ids.has(id)) throw new Error(`${CONTRACT_PATH}: \`conformance.skip\` names ${id}, which has no module in conformance/src/checks: remove the entry`);
    if (typeof why !== 'string' || !why.trim()) throw new Error(`${CONTRACT_PATH}: \`conformance.skip.${id}\` needs the reason Paddock does not run it`);
  }
  const only = mods.map((m) => m.id).filter((id) => !(id in skip));
  for (const id of c.strict ?? []) {
    if (!only.includes(id)) throw new Error(`${CONTRACT_PATH}: \`conformance.strict\` names ${id}, which does not run (no module, or skipped)`);
  }
  c.only = only;
  return `${JSON.stringify(json, null, 2)}\n`;
}

/** A table cell: one line, `|` escaped. */
const cell = (v) => String(v ?? '').replace(/\s+/g, ' ').trim().replace(/\|/g, '\\|');

/**
 * conformance/README.md with the check index between README_BEGIN and README_END rewritten from `metas`
 * (`[{ id, title, scope, mode, needs }]`, in id order). Throws when the markers are missing or out of order.
 */
export function readmeText(text, metas) {
  const begin = text.indexOf(README_BEGIN);
  const end = text.indexOf(README_END);
  if (begin < 0 || end < begin) throw new Error(`${README_PATH} needs the lines ${README_BEGIN} and ${README_END}, in that order, around the check index`);
  const rows = [
    '| Id | Title | Scope | Mode | Needs |',
    '|---|---|---|---|---|',
    ...metas.map((m) => `| ${cell(m.id)} | ${cell(m.title)} | ${cell(m.scope)} | ${cell(m.mode)} | ${cell(m.needs ?? 'all')} |`),
  ];
  return `${text.slice(0, begin)}${README_BEGIN}\n${rows.join('\n')}\n${text.slice(end)}`;
}

/**
 * Every generated file: `[{ path, text }]`, for the module file names `files`, the current contract and README texts, and the
 * modules' metadata `metas` (`[{ id, title, scope, mode, needs }]`, by id).
 */
export function generate(files, contract, readme, metas) {
  const mods = modules(files);
  const byId = new Map(metas.map((m) => [m.id, m]));
  return [
    { path: INDEX_PATH, text: indexText(mods) },
    { path: CONTRACT_PATH, text: contractText(contract, mods) },
    { path: README_PATH, text: readmeText(readme, mods.map((m) => byId.get(m.id) ?? { id: m.id })) },
  ];
}

/**
 * The lines that differ between `got` (the file) and `want` (the generated text), for an error message: `+ line` to add and
 * `- line` to remove. When both hold the same lines (order or duplicates differ), the first line that differs by position.
 */
export function lineDiff(got, want) {
  const gl = got.split('\n');
  const wl = want.split('\n');
  const g = new Set(gl);
  const w = new Set(wl);
  const out = [...wl.filter((l) => !g.has(l)).map((l) => `+ ${l}`), ...gl.filter((l) => !w.has(l)).map((l) => `- ${l}`)];
  if (out.length || got === want) return out;
  const i = wl.findIndex((l, k) => l !== gl[k]);
  const at = i < 0 ? wl.length : i;
  return [`line ${at + 1} (same lines, other order or count): + ${wl[at] ?? '(end of file)'}`, `line ${at + 1}: - ${gl[at] ?? '(end of file)'}`];
}
