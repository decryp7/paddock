// The ADR index of docs/adr/README.md, derived from the ADR files themselves (ER-40, ER-42): number from the file name, title
// from the `# N. Title` heading, status from the first `Status:` line, date from the `Date:` line (else the first date in the
// status line). Adding an ADR is adding its file, then running `node conformance/bin/paddock-adr-index.mjs`; two branches that
// each add an ADR no longer edit the same hand-written table lines (train 14, 2026-11-19: a member could not be pulled for it).
// The table sits between two markers in the README; the text around them is hand-written. Pure over texts: the bin reads and writes.

/** An ADR file name in docs/adr: `NNNN-slug.md`. */
export const ADR_FILE = /^(\d{4})-[a-z0-9][a-z0-9-]*\.md$/;

/** The command that rewrites the index, as the errors print it. */
export const REGENERATE = 'node conformance/bin/paddock-adr-index.mjs';

export const README_PATH = 'docs/adr/README.md';
export const README_BEGIN = `<!-- adrs:begin (generated by ${REGENERATE} from the ADR files; do not edit) -->`;
export const README_END = '<!-- adrs:end -->';

const STATUS_WORDS = ['accepted', 'proposed', 'deferred', 'withdrawn', 'superseded', 'rejected', 'draft', 'implemented'];
const DATE = /\d{4}-\d{2}-\d{2}/;

const cell = (s) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

/**
 * The index entry of one ADR: `{ number, file, title, status, date }`. Throws with the file and the next step when the
 * heading is not `# N. Title` (a number that disagrees with the file name is refused too).
 */
export function entryOf(file, text) {
  const m = ADR_FILE.exec(file);
  if (!m) throw new Error(`docs/adr/${file} is not named NNNN-slug.md (four digits, lower-case slug)`);
  const lines = text.split('\n');
  const h = /^#\s+0*(\d+)\.\s+(.+?)\s*$/.exec(lines[0] ?? '');
  if (!h) throw new Error(`docs/adr/${file}: the first line must be "# <number>. <title>"; add the heading`);
  if (Number(h[1]) !== Number(m[1])) throw new Error(`docs/adr/${file}: the heading says ADR ${h[1]}, the file name ${m[1]}; make them agree`);
  const head = lines.slice(0, 40);
  const statusLine = head.find((l) => /^(-\s*)?\*{0,2}Status:?\*{0,2}:?\s/i.test(l)) ?? '';
  const statusText = statusLine.replace(/^(-\s*)?\*{0,2}Status:?\*{0,2}:?\s*/i, '');
  const word = STATUS_WORDS.find((w) => new RegExp(`\\b${w}\\b`, 'i').test(statusText.slice(0, 60)));
  const status = word ? word[0].toUpperCase() + word.slice(1) : statusText ? statusText.slice(0, 40) : 'No status line';
  const dateLine = head.find((l) => /^(-\s*)?\*{0,2}Date:?\*{0,2}:?\s/i.test(l)) ?? '';
  const date = DATE.exec(dateLine)?.[0] ?? DATE.exec(statusText)?.[0] ?? '';
  return { number: m[1], file, title: h[2], status, date };
}

/** The generated table for `entries`, in number order. */
export function tableText(entries) {
  const rows = [...entries]
    .sort((a, b) => a.number.localeCompare(b.number))
    .map((e) => `| [${e.number}](${e.file}) | ${cell(e.title)} | ${cell(e.status)} | ${e.date} |`);
  return ['| # | Decision | Status | Date |', '|---|---|---|---|', ...rows].join('\n');
}

/** `readme` with the text between its two markers replaced by the table of `entries`. Throws when a marker is missing. */
export function readmeText(readme, entries) {
  const b = readme.indexOf(README_BEGIN);
  const e = readme.indexOf(README_END);
  if (b < 0 || e < b) throw new Error(`${README_PATH} needs the lines "${README_BEGIN}" and "${README_END}" around the index`);
  return `${readme.slice(0, b + README_BEGIN.length)}\n${tableText(entries)}\n${readme.slice(e)}`;
}

/** The ADR files among `names` (a folder listing): ADR files in order; other `.md` files are notes and are skipped. */
export function adrFiles(names) {
  return names.filter((n) => /^\d/.test(n) && n.endsWith('.md')).sort();
}
