// The lists that name every conformance check, derived from the check modules (ER-40, ER-42): the modules in
// conformance/src/checks (`C<n>-<slug>.mjs`, each exporting its id, scope and mode) are the one registry. From them this
// module derives
//
//   - conformance/src/checks/index.mjs: one import per module and the `checks` list, in id order;
//   - `conformance.only` of conformance/paddock.ci.json: every check, in id order, except the ones `conformance.skip` names
//     with the reason Paddock does not run them on its own tree.
//
// Adding a check is: write the module (its id from `./dev check new-id --reserve <branch>`), then run
// `node conformance/bin/paddock-check-lists.mjs`. `--check` (the generator registry's `conformance-check-lists` entry and
// test/check-lists.test.mjs) fails when either list is stale and prints that command. Everything here is pure over texts;
// bin/paddock-check-lists.mjs does the reading and writing.

/** A check module's file name: `C<n>-<slug>.mjs`. */
export const MODULE = /^C(\d+)-[a-z0-9][a-z0-9-]*\.mjs$/;

/** The command that rewrites both lists, as the errors print it. */
export const REGENERATE = 'node conformance/bin/paddock-check-lists.mjs';

/** The repository paths of the generated lists. */
export const INDEX_PATH = 'conformance/src/checks/index.mjs';
export const CONTRACT_PATH = 'conformance/paddock.ci.json';

/**
 * The check modules among `files` (the names in conformance/src/checks), in id order: `[{ id, n, file }]`. Throws on two modules
 * with one id, so a clash between branches fails at the regenerate, not at run time.
 */
export function modules(files) {
  const out = [];
  const seen = new Map();
  for (const file of files) {
    const m = MODULE.exec(file);
    if (!m) continue;
    const id = `C${m[1]}`;
    if (seen.has(id)) throw new Error(`check id ${id} has two modules (${seen.get(id)} and ${file}): renumber one with \`./dev check new-id --reserve <branch>\``);
    seen.set(id, file);
    out.push({ id, n: Number(m[1]), file });
  }
  return out.sort((a, b) => a.n - b.n);
}

/** The text of conformance/src/checks/index.mjs for these modules. */
export function indexText(mods) {
  const lines = [
    `// Generated by ${REGENERATE} from the check modules in this folder. Do not edit:`,
    '// add a check by writing its module (C<n>-<slug>.mjs), then run the command.',
    ...mods.map((m) => `import ${m.id} from './${m.file}';`),
    '',
    '/** Every check, in id order. A check is { id, title, rule, run(ctx) -> findings[] | Promise<findings[]> }. */',
    `export const checks = [${mods.map((m) => m.id).join(', ')}];`,
    '',
  ];
  return lines.join('\n');
}

/**
 * conformance/paddock.ci.json with `conformance.only` rewritten: every module's id in id order, less `conformance.skip`'s keys.
 * Throws when `skip` is missing, names a check that has no module, or gives no reason, and when `strict` names a check that
 * does not run.
 */
export function contractText(text, mods) {
  const json = JSON.parse(text);
  const c = json.conformance;
  if (!c || typeof c !== 'object') throw new Error(`${CONTRACT_PATH} has no \`conformance\` object`);
  const skip = c.skip;
  if (!skip || typeof skip !== 'object' || Array.isArray(skip)) {
    throw new Error(`${CONTRACT_PATH}: \`conformance.skip\` must be an object of check id to the reason Paddock does not run it`);
  }
  const ids = new Set(mods.map((m) => m.id));
  for (const [id, why] of Object.entries(skip)) {
    if (!ids.has(id)) throw new Error(`${CONTRACT_PATH}: \`conformance.skip\` names ${id}, which has no module in conformance/src/checks: remove the entry`);
    if (typeof why !== 'string' || !why.trim()) throw new Error(`${CONTRACT_PATH}: \`conformance.skip.${id}\` needs the reason Paddock does not run it`);
  }
  const only = mods.map((m) => m.id).filter((id) => !(id in skip));
  for (const id of c.strict ?? []) {
    if (!only.includes(id)) throw new Error(`${CONTRACT_PATH}: \`conformance.strict\` names ${id}, which does not run (no module, or skipped)`);
  }
  c.only = only;
  return `${JSON.stringify(json, null, 2)}\n`;
}

/**
 * Both generated files for the module names `files` and the contract text: `[{ path, text }]`.
 */
export function generate(files, contract) {
  const mods = modules(files);
  return [
    { path: INDEX_PATH, text: indexText(mods) },
    { path: CONTRACT_PATH, text: contractText(contract, mods) },
  ];
}

/** The lines that differ between `want` and `got` (one line per added or removed line), for an error message. */
export function lineDiff(got, want) {
  const g = new Set(got.split('\n'));
  const w = new Set(want.split('\n'));
  return [...want.split('\n').filter((l) => !g.has(l)).map((l) => `+ ${l}`), ...got.split('\n').filter((l) => !w.has(l)).map((l) => `- ${l}`)];
}
