// C99 (ADR 0057, rule 72): no shipped Paddock process uses the macOS Keychain. Ad-hoc and self-signed builds lose silent
// Keychain access on every update; a read or write of an older build's item raises a password dialog and a blocked call
// waits with no time limit and no window.
//
// Built here (ADR 0057 §3, layers 1 and 2):
// 1. Manifest scan of every Cargo.toml that ships (fuzz targets, research harnesses, spikes, tools/paddock-dev and
//    conformance fixtures are not shipped). A table names a crate in its body (a dependency, a renamed one with `package`,
//    a feature entry such as `paddock-secrets/keyring` or `paddock-secrets?/keyring`) or in its header
//    (`[dependencies.keyring]`).
//    - One door: outside paddock-secrets, `keyring`, `keyring-core` and the keyring store crates fail under any cfg.
//    - macOS: the `paddock-secrets/keyring` feature, `security-framework`, `security-framework-sys` and `objc2-security`
//      fail unless the table's cfg is one of not(target_os = "macos"), windows, target_os = "windows",
//      target_os = "linux".
//    - Exempt: paddock-secrets itself (defines the feature) and paddock-workspace-hack (generated by hakari, no code).
// 2. Source scan of the code a release ships (.rs .c .cc .cpp .m .mm .h .swift, the .ts under app/src and ui/projects, and the
//    Tauri capability files): the SecItem/SecKeychain symbols, a `security` subcommand that touches a keychain, and a
//    capability shell scope that runs `security`.
// Positive controls (ER-33): a tree with a Cargo.toml but no source file read, a tree with no Cargo.toml whose CI contract
// does not say "no Rust", and a file that cannot be read are each "check broken", never a pass.
//
// 3. and 4. For each workspace a paddock.ci.json names, and crates/: `cargo fetch`, `cargo metadata` and
//    `cargo tree --target <Apple triple>` on both Apple triples (util/keychain-graph.mjs). The keyring crates fail anywhere
//    in that graph, a Keychain binding crate fails below a parent or series nobody reviewed, objc2-security fails with a
//    Keychain feature on, and the sources of every other dependency are read for the Keychain symbols. A graph finding has
//    its own path (`<dir>/Cargo.lock#<key>`) so a waiver names exactly that finding. A failed fetch, an unreadable graph or a
//    missing Cargo.lock is "check broken" or "not measured": an error no waiver covers (ER-33).
// `--scope apps/<app>` (the release path, ER-31): only that app's files, crates/ and the UI projects it ships (ui/projects/<app>, ui/projects/paddock-ui) are read, so another app's finding cannot
//    block this app's release; a scope matching no file is an unwaivable broken check. CI's c99 job runs the whole repository.
// 5. The Clippy entries (lint/clippy.toml, compared by C13) ban the Keychain API paths and types in the app's own code.
//    Recorded deviation (ADR 0057 §3.5): the two demos (apps/shell-demo, apps/workbench-demo) have no clippy.toml and keep
//    none, so Clippy on macOS is NOT MEASURED for them; this check says so (a warning at `Cargo.lock#clippy-not-measured`)
//    for every probed workspace without one. Their manifests, graphs and sources are still covered by layers 1 to 4.
//    A binary that ships in a dependency and is not reviewed (REVIEWED_BINARIES) is an error. The scan of the real
//    security-framework source is a positive control on every probe whose graph has it, and the run fails closed: if no
//    probed graph has security-framework the control never ran, which is an unwaivable broken check.
import { join, posix } from 'node:path';
import { error, unwaivable, warn } from '../finding.mjs';

// An input the check could not read (a file, cargo, the network, a scope with no file) is "not measured" (exit 6); a failed positive control is "check broken" (exit 7).
const cannotRead = (f) => unwaivable(f, 'not-measured');
import { tomlTables } from '../sync/baseline.mjs';
import { inScope, normalizeScope } from '../util/scope.mjs';
import { graphFindings, MACOS_ONLY_BANNED, ONE_DOOR, probeWorkspace, readGraph, SYMBOLS, sourceScan } from '../util/keychain-graph.mjs';

/** Paths that never ship: their manifests and sources are not checked. */
const NOT_SHIPPED = [/(^|\/)fuzz\//, /^tools\/paddock-dev\//, /(^|\/)harness\//, /^spikes\//, /^conformance\//, /(^|\/)node_modules\//];

const OFF_MACOS = new Set(['not(target_os = "macos")', 'windows', 'target_os = "windows"', 'target_os = "linux"']);
const EXEMPT = new Set(['paddock-secrets', 'paddock-workspace-hack']);

const SOURCE = /\.(rs|c|cc|cpp|m|mm|h|swift)$/;
const TS = /^(.*\/)?(app\/src|ui\/projects)\/.*\.ts$/;
const CAPABILITY = /(^|\/)src-tauri\/capabilities\/[^/]+\.json$/;

const SUBCOMMANDS = /\b((?:find|add|delete)-(?:generic|internet)-password|find-certificate|find-identity|delete-certificate|delete-identity|add-trusted-cert|create-keychain|unlock-keychain|dump-keychain)\b/g;
// `import` and `export` are common words: only right after `security` (as in `security export` or ["security", "export"]).
const IMPORT_EXPORT = /\bsecurity\b["'`]?\s*[,)]?\s*["'`]?(import|export)\b/g;

/** The cfg of a table header (`[target.'cfg(windows)'.dependencies]` gives `windows`), or null for every target. */
function cfgOf(header) {
  const m = /^\[target\.(['"])(.*)\1\./.exec(header);
  if (!m) return /^\[target\.([\w-]+)\./.exec(header)?.[1] ?? null; // a bare target triple
  const c = /^cfg\((.*)\)$/.exec(m[2]);
  return c ? c[1].trim() : m[2];
}

/** Whether a table's cfg (or target triple) can never be macOS. */
const offMacos = (cfg) => cfg !== null && (OFF_MACOS.has(cfg) || /^[\w]+-[\w]+-(windows|linux)[\w-]*$/.test(cfg));

/** The package name declared in a manifest's [package] table, or null. */
function packageName(tables) {
  const pkg = tables.find((t) => t.header === '[package]');
  for (const l of pkg?.lines ?? []) {
    const m = /^\s*name\s*=\s*"([^"]+)"/.exec(l);
    if (m) return m[1];
  }
  return null;
}

/** Strips a TOML comment (no `#` inside strings in the lines this check reads). */
const code = (l) => l.replace(/#.*$/, '');

/**
 * The crates and features a table names, each with its line (1-based in the file): [{ line, crate } | { line, feature }].
 * `start` is the 0-based line of the table's header in the file.
 */
function named(table, start) {
  const out = [];
  const isDeps = /dependencies/.test(table.header);
  const headerCrate = /dependencies\.([\w-]+)\]$/.exec(table.header)?.[1];
  if (headerCrate) out.push({ line: start + 1, crate: headerCrate });
  table.lines.forEach((raw, i) => {
    if (i === 0) return;
    const l = code(raw);
    const line = start + i + 1;
    if (isDeps && !headerCrate) {
      const key = /^\s*([\w-]+)(\.workspace)?\s*=/.exec(l)?.[1];
      if (key) out.push({ line, crate: key });
      const pkg = /\bpackage\s*=\s*"([^"]+)"/.exec(l)?.[1];
      if (pkg && pkg !== key) out.push({ line, crate: pkg });
      // `paddock-secrets = { ..., features = ["keyring"] }`
      if (key === 'paddock-secrets' && /\bfeatures\s*=\s*\[[^\]]*"keyring"/.test(l)) out.push({ line, feature: 'paddock-secrets/keyring' });
    }
    if (headerCrate) {
      const pkg = /^\s*package\s*=\s*"([^"]+)"/.exec(l)?.[1];
      if (pkg) out.push({ line, crate: pkg });
      if ((pkg ?? headerCrate) === 'paddock-secrets' && /^\s*features\s*=\s*\[[^\]]*"keyring"/.test(l)) out.push({ line, feature: 'paddock-secrets/keyring' });
    }
    for (const m of l.matchAll(/"paddock-secrets\??\/keyring"/g)) out.push({ line, feature: 'paddock-secrets/keyring', at: m.index });
  });
  return out;
}

/** What a manifest names that rule 72 forbids: [{ line, what }]. Pure. */
export function manifestFindings(file, text) {
  const { tables } = tomlTables(text);
  if (EXEMPT.has(packageName(tables))) return [];
  const lines = text.split('\n');
  const out = [];
  let from = 0;
  for (const t of tables) {
    const start = lines.indexOf(t.lines[0], from);
    from = start + 1;
    const off = offMacos(cfgOf(t.header));
    for (const n of named(t, start)) {
      if (n.crate && ONE_DOOR.has(n.crate)) out.push({ line: n.line, what: `${n.crate} (only paddock-secrets may use it)` });
      else if (!off && n.crate && MACOS_ONLY_BANNED.has(n.crate)) out.push({ line: n.line, what: `${n.crate} on macOS` });
      else if (!off && n.feature) out.push({ line: n.line, what: `${n.feature} on macOS` });
    }
  }
  return out;
}

/** The Keychain uses in one source or capability file: [{ line, what }]. Pure. */
export function sourceFindings(file, text) {
  const out = [];
  const lineAt = (i) => text.slice(0, i).split('\n').length;
  if (CAPABILITY.test(file)) {
    if (/"(cmd|name)"\s*:\s*"(\/usr\/bin\/)?security"/.test(text) && /shell:/.test(text)) out.push({ line: 1, what: 'a shell scope that runs security' });
    return out;
  }
  for (const m of text.matchAll(SYMBOLS)) out.push({ line: lineAt(m.index), what: m[1] });
  for (const m of text.matchAll(SUBCOMMANDS)) out.push({ line: lineAt(m.index), what: `security ${m[1]}` });
  for (const m of text.matchAll(IMPORT_EXPORT)) out.push({ line: lineAt(m.index), what: `security ${m[1]}` });
  return out.sort((a, b) => a.line - b.line);
}

const shipped = (f) => !NOT_SHIPPED.some((re) => re.test(f));

export default {
  id: 'C99',
  title: 'No shipped process uses the macOS Keychain (rule 72)',
  rule: 72,
  scope: 'root',
  mode: 'gate',
  run(ctx) {
    // `options.readFile` lets a test make a file unreadable (it returns null for it, undefined to read as usual).
    const read = (f) => {
      const injected = ctx.options.readFile?.(f);
      return injected === undefined ? ctx.read(f) : injected;
    };
    const unreadable = (file) =>
      cannotRead(error('C99', 72, file, 1, `check broken: ${file} could not be read, so a Keychain use in it cannot be seen`, 'Make the file readable (permissions, encoding) and run the check again.'));
    // `--scope apps/<app>`: a release of one app is judged on that app's workspaces and the shared crates/ only (ER-31): another
    // app's findings must not block it. A scope that matches no file is a broken check, never an empty pass (ER-33).
    const scope = normalizeScope(ctx.options.scope);
    const all = ctx.files().filter(shipped);
    if (scope && !all.some((f) => f.startsWith(`${scope}/`))) {
      return [cannotRead(error('C99', 72, '.', 1, `check broken: --scope ${scope} matches no file, so nothing was checked`, 'Name the app folder as it is in the repository (apps/<app>).'))];
    }
    const files = all.filter((f) => inScope(scope, f));
    const manifests = files.filter((f) => f === 'Cargo.toml' || f.endsWith('/Cargo.toml'));
    if (!manifests.length) {
      // No Rust is a pass only when the app's CI contract says so (no `cargo` field); otherwise the scan saw nothing (ER-33).
      const contract = ctx.read('paddock.ci.json');
      let noRust = false;
      try {
        noRust = contract !== null && JSON.parse(contract).cargo === undefined;
      } catch {
        noRust = false;
      }
      return noRust
        ? []
        : [cannotRead(error('C99', 72, '.', 1, 'check broken: no Cargo.toml was found, so the manifest scan read nothing', 'Run the check from the app or repository root, or state "no Rust" by leaving `cargo` out of paddock.ci.json.'))];
    }
    const out = [];
    for (const file of manifests) {
      const text = read(file);
      if (text === null) {
        out.push(unreadable(file));
        continue;
      }
      for (const f of manifestFindings(file, text)) {
        out.push(error('C99', 72, file, f.line, `${file} names ${f.what}: a shipped process must not reach the macOS Keychain`,
          'Use the paddock-secrets Secrets port (an owner-only file on macOS); enable paddock-secrets/keyring only under cfg(not(target_os = "macos")) and never depend on keyring or the Keychain crates directly (ADR 0057).'));
      }
    }
    const sources = files.filter((f) => SOURCE.test(f) || TS.test(f) || CAPABILITY.test(f));
    if (!files.some((f) => /\.rs$/.test(f))) {
      out.push(unwaivable(error('C99', 72, manifests[0], 1, 'check broken: there are Cargo manifests but the source scan read no .rs file, so it cannot see a Keychain call',
        'Run the check from the folder that holds the sources (the app or the repository root).')));
    }
    for (const file of sources) {
      const text = read(file);
      if (text === null) {
        out.push(unreadable(file));
        continue;
      }
      for (const f of sourceFindings(file, text)) {
        out.push(error('C99', 72, file, f.line, `${file} uses ${f.what}: a shipped process must not reach the macOS Keychain`,
          'Keep the secret in an owner-only file through paddock-secrets (FileSecrets or SecretFile) instead (ADR 0057, rule 72).'));
      }
    }
    out.push(...graphLayers(ctx, files));
    return out;
  },
};

/** The Cargo workspace folders to probe: each paddock.ci.json's `cargo` folder, and crates/ (the shared libraries). */
function workspaces(ctx, files) {
  const dirs = new Map();
  for (const f of files.filter((x) => x === 'paddock.ci.json' || x.endsWith('/paddock.ci.json'))) {
    let cargo;
    try {
      cargo = JSON.parse(ctx.read(f) ?? '{}').cargo;
    } catch {
      continue;
    }
    if (typeof cargo !== 'string') continue;
    const dir = posix.normalize(posix.join(posix.dirname(f), cargo)).replace(/\/$/, '');
    dirs.set(dir, { dir, allFeatures: true });
  }
  if (files.includes('crates/Cargo.lock')) dirs.set('crates', { dir: 'crates', allFeatures: false });
  return [...dirs.values()];
}

/** Whether `dir` or a folder above it holds a clippy.toml (Clippy reads the nearest one). */
function hasClippyConfig(files, dir) {
  for (let d = dir; ; d = posix.dirname(d)) {
    const prefix = d === '.' ? '' : `${d}/`;
    if (files.includes(`${prefix}clippy.toml`) || files.includes(`${prefix}.clippy.toml`)) return true;
    if (d === '.' || d === '/') return false;
  }
}

/** Layers 3 and 4 over the macOS graph of every declared workspace, on both Apple triples. */
function graphLayers(ctx, files) {
  if (ctx.options.graph === 'off') return [];
  if (ctx.options.graph === 'skipped') {
    return [warn('C99', 72, '.', 1, 'not measured: the macOS dependency graph layers were skipped (--no-graph); only the manifest and source scans ran', 'Run without --no-graph where the cargo registry is reachable; CI never skips them.')];
  }
  const lockOf = (dir) => (dir === '.' ? 'Cargo.lock' : `${dir}/Cargo.lock`);
  const spaces = workspaces(ctx, files);
  const out = [];
  // Neither of these can be waived: a waiver would hide that the check looked at nothing (ER-33).
  const broken = (lock, dir, why) => cannotRead(error('C99', 72, lock, 1, `check broken: the macOS dependency graph of ${dir} could not be read (${why}), so a Keychain use in a dependency cannot be seen`, 'Fix the cause (network to the registry, a Cargo.lock that is out of date, cargo on PATH) and run the check again.'));
  const notMeasured = (what, fix) => unwaivable(error('C99', 72, '.', 1, `not measured: ${what}, so the macOS dependency graph was not probed`, fix), 'not-measured');
  if (!spaces.length) return [notMeasured('no paddock.ci.json names a Cargo workspace', 'Name the workspace in the app\'s paddock.ci.json (`cargo`).')];
  let control = false;
  for (const { dir, allFeatures } of spaces) {
    const lock = lockOf(dir);
    if (!files.includes(lock)) {
      out.push(notMeasured(`${lock} does not exist`, 'Commit the Cargo.lock of every app workspace (CI installs from it).'));
      continue;
    }
    const probe = ctx.options.probe ?? ((d) => probeWorkspace(d, { extra: ctx.options.cargoArgs ?? [], allFeatures }));
    const r = probe(join(ctx.root, dir));
    if (r.broken) {
      out.push(broken(lock, dir, r.broken));
      continue;
    }
    const merged = new Map();
    const findings = new Map();
    let bad = false;
    for (const run of r.runs) {
      const graph = readGraph(r.meta, run.tree);
      if (graph.broken) {
        out.push(broken(lock, dir, `${run.target}: ${graph.broken}`));
        bad = true;
        break;
      }
      for (const p of graph.crates) merged.set(`${p.name}@${p.version}`, p);
      for (const f of graphFindings(graph)) if (!findings.has(f.key)) findings.set(f.key, { ...f, target: run.target });
    }
    if (bad) continue;
    for (const f of findings.values()) {
      out.push(error('C99', 72, `${lock}#${f.key}`, 1, `${dir}: ${f.what} (${f.target})`, 'Keep the Keychain out of the macOS build: use paddock-secrets (an owner-only file on macOS); for a new reviewed TLS or OS parent, add it to BINDING_PARENTS in conformance/src/util/keychain-graph.mjs after reading what it calls (ADR 0057). A waiver names this exact path.'));
    }
    const scan = sourceScan({ crates: [...merged.values()] }, ctx.options);
    if (scan.unfetched.length) out.push(broken(lock, dir, `the sources of ${scan.unfetched.length} crates were not downloaded, for example ${scan.unfetched.slice(0, 3).join(', ')}`));
    else if ([...merged.values()].some((p) => p.source) && scan.read === 0) out.push(broken(lock, dir, 'the source scan read no file of any dependency'));
    for (const f of scan.findings) {
      out.push(error('C99', 72, `${lock}#${f.key}`, 1, `${dir}: dependency ${f.what}: a shipped process must not reach the macOS Keychain`, 'Remove or replace the dependency (or its feature) that calls the Keychain; a binding that only evaluates TLS trust never uses SecItem or SecKeychain symbols.'));
    }
    for (const b of scan.binaries) {
      out.push(error('C99', 72, `${lock}#${b.key}`, 1, `${dir}: binary, not scanned: ${b.what}`, 'A prebuilt binary cannot be read for Keychain calls: read what it is, then add the crate and series to REVIEWED_BINARIES (conformance/src/util/keychain-graph.mjs), or waive this exact path with a reason.'));
    }
    // Positive control (ER-33), on the real sources of every probe: the scan must see a Keychain call in security-framework
    // (it binds SecKeychainSetUserInteractionAllowed), or it cannot be trusted to see one elsewhere.
    const sf = [...merged.values()].find((p) => p.name === 'security-framework');
    if (sf) {
      const probeResult = sourceScan({ crates: [sf] }, { ...ctx.options, scanBindings: true });
      if (!probeResult.findings.some((f) => f.key.endsWith(':SecKeychainSetUserInteractionAllowed'))) {
        out.push(broken(lock, dir, `the source scan did not find SecKeychainSetUserInteractionAllowed in ${sf.name}@${sf.version}, so it cannot be trusted to see a Keychain call`));
      } else control = true;
    }
    if (!hasClippyConfig(files, dir)) {
      out.push(warn('C99', 72, `${lock}#clippy-not-measured`, 1, `${dir}: Clippy on macOS: not measured (no clippy.toml at ${dir} or above it), so the Keychain API bans (layer 5) do not apply to its own code`, 'Add a clippy.toml with the Keychain entries of lint/clippy.toml, or leave this recorded deviation (the demos, ADR 0057 §3.5).'));
    }
  }
  // Fail closed: if no probed graph holds security-framework, the scan was never shown a real Keychain call (ER-33).
  if (!control && !out.some((f) => f.unwaivable)) {
    out.push(unwaivable(error('C99', 72, '.', 1, 'check broken: no probed macOS graph contains security-framework, so the source scan was never shown to see a real Keychain call (SecKeychainSetUserInteractionAllowed)', 'Probe a workspace whose graph has security-framework (every app with TLS does), or fix the probe so it reads the dependency graph.')));
  }
  return out;
}
