import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';
import { commitLintMain, lint } from '../src/commit-lint.mjs';
import { findingsOf, makeApp, messages } from './helpers.mjs';

test('lint good: Conventional Commits, scope, breaking mark, merge commits', () => {
  for (const m of ['feat: add x', 'fix(core): y\n\nBody text.', 'chore!: drop z', 'Merge branch main', 'docs: a [skip ci]']) assert.deepEqual(lint(m), [], m);
});

test('lint bad: header shape, long header, missing blank line, empty', () => {
  assert.match(lint('Added a thing')[0], /does not start with/);
  assert.match(lint(`feat: ${'x'.repeat(100)}`)[0], /first line is/);
  assert.match(lint('feat: ok\nbody')[0], /second line must be empty/);
  assert.match(lint('')[0], /empty/);
});

test('lint bad: Co-Authored-By and AI attribution, in any case and position', () => {
  const bodies = [
    'Co-Authored-By: Someone <a@b.c>',
    'co-authored-by: Claude <noreply@anthropic.com>',
    'Generated with Claude Code',
    'Generated by ChatGPT',
    'Claude-Session: https://claude.ai/code/session_01',
    'see https://claude.ai/code/session_01ABC',
    '\u{1F916} Generated with an AI tool',
  ];
  for (const b of bodies) assert.ok(lint(`fix: thing\n\n${b}\n`).some((p) => /co-author or AI attribution/.test(p)), b);
  // A merge commit is still not allowed to carry attribution.
  assert.ok(lint('Merge x\n\nCo-Authored-By: a <b@c>').length > 0);
});

test('lint does not flag ordinary words', () => {
  assert.deepEqual(lint('fix: handle claude desktop config file\n\nThe AI summary pane no longer crashes.'), []);
});

test('commitLintMain: --file and --range, exit codes', () => {
  const dir = makeApp({ 'm.txt': 'feat: ok\n', 'bad.txt': 'feat: ok\n\nCo-Authored-By: x <y@z>\n' });
  const log = [];
  assert.equal(commitLintMain(['--file', join(dir, 'm.txt')], dir, (l) => log.push(l)), 0);
  assert.equal(commitLintMain(['--file', join(dir, 'bad.txt')], dir, (l) => log.push(l)), 1);
  assert.equal(commitLintMain(['--nope'], dir, (l) => log.push(l)), 2);
  assert.equal(commitLintMain(['--file', join(dir, 'missing.txt')], dir, (l) => log.push(l)), 2);
  assert.match(log.join('\n'), /Co-Authored-By|co-author or AI/);
});

function repo(messages) {
  const dir = makeApp({ 'a.txt': 'x' });
  const git = (...a) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.test', '-c', 'commit.gpgsign=false', ...a], { cwd: dir, stdio: 'pipe' });
  git('init', '-q');
  messages.forEach((m, i) => {
    writeFileSync(join(dir, 'a.txt'), String(i));
    git('add', '.');
    git('commit', '-q', '-m', m);
  });
  return dir;
}

test('C23 good: a clean history', async () => {
  assert.deepEqual(await findingsOf('C23', repo(['feat: one', 'fix: two'])), []);
});

test('C23 bad: a history with a Co-Authored-By commit and a free-form subject', async () => {
  const f = await findingsOf('C23', repo(['feat: one', 'fix: two\n\nCo-Authored-By: A <a@example.test>', 'did stuff']));
  assert.equal(f.length, 2);
  assert.match(messages(f), /Co-Authored-By trailer/);
  assert.match(messages(f), /does not start with/);
});

test('C23 warns instead of passing silently when there is no history', async () => {
  const f = await findingsOf('C23', makeApp({ 'a.txt': 'x' }));
  assert.equal(f[0].severity, 'warn');
});
