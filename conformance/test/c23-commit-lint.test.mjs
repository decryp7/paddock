test('lint good: Conventional Commits, scope, breaking mark, merge commits', () => {
  for (const m of ['feat: add x', 'fix(core): y\n\nBody text.', 'fix(spotter,debrief): both apps', 'chore!: drop z', 'Merge branch main', 'docs: a [skip ci]']) assert.deepEqual(lint(m), [], m);
});

test('lint bad: header shape, long header, missing blank line, empty', () => {
  assert.match(lint('Added a thing')[0], /does not start with/);
  assert.match(lint('fix(a,): x')[0], /does not start with/);
  assert.match(lint('fix(a, b): x')[0], /does not start with/);
  assert.match(lint(`feat: ${'x'.repeat(100)}`)[0], /first line is/);
  assert.match(lint('feat: ok\nbody')[0], /second line must be empty/);
  assert.match(lint('')[0], /empty/);
});

test('lint bad: Co-Authored-By and AI attribution, in any case and position', () => {
  const bodies = [
    'Co-Authored-By: Someone <a@b.c>',
    'co-authored-by: Claude <noreply@anthropic.com>',
    'Generated with Claude Code',
    'Generated by ChatGPT',
    'Claude-Session: https://claude.ai/code/session_01',
    'see https://claude.ai/code/session_01ABC',
    '\u{1F916} Generated with an AI tool',
  ];
  for (const b of bodies) assert.ok(lint(`fix: thing\n\n${b}\n`).some((p) => /co-author or AI attribution/.test(p)), b);
  // A merge commit is still not allowed to carry attribution.
  assert.ok(lint('Merge x\n\nCo-Authored-By: a <b@c>').length > 0);
});

test('lint does not flag ordinary words', () => {
  assert.deepEqual(lint('fix: handle claude desktop config file\n\nThe AI summary pane no longer crashes.'), []);
});

test('commitLintMain: --file and --range, exit codes', () => {
  const dir = makeApp({ 'm.txt': 'feat: ok\n', 'bad.txt': 'feat: ok\n\nCo-Authored-By: x <y@z>\n' });
  const log = [];
  assert.equal(commitLintMain(['--file', join(dir, 'm.txt')], dir, (l) => log.push(l)), 0);
  assert.equal(commitLintMain(['--file', join(dir, 'bad.txt')], dir, (l) => log.push(l)), 1);
  assert.equal(commitLintMain(['--nope'], dir, (l) => log.push(l)), 2);
  assert.equal(commitLintMain(['--file', join(dir, 'missing.txt')], dir, (l) => log.push(l)), 2);
  assert.match(log.join('\n'), /Co-Authored-By|co-author or AI/);
});

function repo(messages) {
  const dir = makeApp({ 'a.txt': 'x' });
  const git = (...a) => execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.test', '-c', 'commit.gpgsign=false', ...a], { cwd: dir, stdio: 'pipe' });
  git('init', '-q');
  messages.forEach((m, i) => {
    writeFileSync(join(dir, 'a.txt'), String(i));
    git('add', '.');
    git('commit', '-q', '-m', m);
  });
  return dir;
}

test('C23 good: a clean history', async () => {
  assert.deepEqual(await findingsOf('C23', repo(['feat: one', 'fix: two'])), []);
});

test('C23 bad: a history with a Co-Authored-By commit and a free-form subject', async () => {
  const f = await findingsOf('C23', repo(['feat: one', 'fix: two\n\nCo-Authored-By: A <a@example.test>', 'did stuff']));
  assert.equal(f.length, 2);
  assert.match(messages(f), /Co-Authored-By trailer/);
  assert.match(messages(f), /does not start with/);
});

test('C23 warns instead of passing silently when there is no history', async () => {
  const f = await findingsOf('C23', makeApp({ 'a.txt': 'x' }));
  assert.equal(f[0].severity, 'warn');
});

// commit-lint honours the C23 waivers of paddock.waivers.toml (the file and format the conformance run uses).
function waiverRepo(waiver) {
  const dir = repo(['feat: one', 'wip: not conventional', 'fix: three']);
  const sha = execFileSync('git', ['rev-parse', 'HEAD~1'], { cwd: dir, encoding: 'utf8' }).trim();
  if (waiver) writeFileSync(join(dir, 'paddock.waivers.toml'), waiver(sha));
  return { dir, sha };
}
const W = (path, expires = '2999-01-01') => `[[waiver]]\ncheck = "C23"\npath = "${path}"\nreason = "unshared branch"\nexpires = "${expires}"\n`;
const run = (dir, range = 'HEAD') => {
  const log = [];
  return { code: commitLintMain(['--range', range], dir, (l) => log.push(l), new Date('2027-01-01T00:00:00Z')), out: log.join('\n') };
};

test('commit-lint: an unwaived bad commit fails, a waived one passes and is printed', () => {
  const none = waiverRepo(null);
  assert.equal(run(none.dir).code, 1);
  const short = waiverRepo((sha) => W(`commit ${sha.slice(0, 10)}`));
  const r = run(short.dir);
  assert.equal(r.code, 0, r.out);
  assert.match(r.out, new RegExp(`waived: ${short.sha.slice(0, 10)} wip: not conventional \\(unshared branch\\)`));
  const full = waiverRepo((sha) => W(`commit ${sha}`));
  assert.equal(run(full.dir).code, 0, 'a full sha is accepted too');
  const other = waiverRepo(() => W('commit 0123456789'));
  assert.equal(run(other.dir).code, 1, 'a waiver for another commit waives nothing');
});

test('commit-lint: an expired waiver does not apply and warns; an unused one does not fail', () => {
  const expired = waiverRepo((sha) => W(`commit ${sha.slice(0, 10)}`, '2026-01-01'));
  const r = run(expired.dir);
  assert.equal(r.code, 1);
  assert.match(r.out, /expired/);
  const unused = waiverRepo((sha) => W(`commit ${sha.slice(0, 10)}`));
  assert.equal(run(unused.dir, 'HEAD~1..HEAD').code, 0, 'the waived commit is outside the range: no failure');
  assert.doesNotMatch(run(unused.dir, 'HEAD~1..HEAD').out, /waives nothing|W003/);
});

test('commit-lint: waivers of other checks are ignored, and the conformance run still honours the C23 one', async () => {
  const other = waiverRepo((sha) => `${W(`commit ${sha.slice(0, 10)}`).replace('C23', 'C15')}`);
  assert.equal(run(other.dir).code, 1);
  const w = waiverRepo((sha) => W(`commit ${sha.slice(0, 10)}`));
  const res = await runChecks({ root: w.dir, app: 'demo', only: ['C23'] });
  assert.equal(res.errors, 0, JSON.stringify(res.findings));
  assert.equal(res.waived.length, 1);
});
