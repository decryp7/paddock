import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import { globRegex, parseRegistry, saysGenerated } from '../src/checks/C116-generator-registry.mjs';
import { findingsOf, makeApp } from './helpers.mjs';

const REGISTRY = `version = 1

[[generator]]
id = "notices-x"
what = "notices"
check = ["bash", "n.sh", "--check"]
regenerate = "bash n.sh"
paths = ["apps/x/**"]
outputs = ["apps/x/app/src-tauri/resources/THIRD_PARTY_NOTICES.md", "apps/x/Cargo.lock"]
cost = "heavy"

[[generator]]
id = "ts"
what = "ts"
check = ["cargo", "test"]
regenerate = "PADDOCK_WRITE_TS=1 cargo test"
paths = ["ui/**"]
outputs = [
  "ui/projects/*/generated/*.ts", # the bindings
]
cost = "heavy"
`;

test('C116 reads the outputs of every entry, one line or many', () => {
  const r = parseRegistry(REGISTRY);
  assert.deepEqual(r.map((e) => e.id), ['notices-x', 'ts']);
  assert.deepEqual(r[0].outputs, ['apps/x/app/src-tauri/resources/THIRD_PARTY_NOTICES.md', 'apps/x/Cargo.lock']);
  assert.deepEqual(r[1].outputs, ['ui/projects/*/generated/*.ts']);
});

test('C116 globs: * stays in a folder, ** crosses folders', () => {
  assert.ok(globRegex('a/*/c.ts').test('a/b/c.ts'));
  assert.ok(!globRegex('a/*/c.ts').test('a/b/d/c.ts'));
  assert.ok(globRegex('a/**/c.ts').test('a/c.ts') && globRegex('a/**/c.ts').test('a/b/d/c.ts'));
  assert.ok(!globRegex('a.b').test('aXb'));
});

test('C116 header: a comment that says the file is generated, not a doc comment about generated code', () => {
  assert.ok(saysGenerated('// Generated from the command table. Do not edit.\nexport const A = 1;'));
  assert.ok(saysGenerated('# This file is automatically @generated by Cargo.\n'));
  assert.ok(saysGenerated('; Generated by paddock-service from the spec\n'));
  assert.ok(!saysGenerated('//! The generated TypeScript of the crate, checked on every test run.\n'));
  assert.ok(!saysGenerated('header = "# Changelog\\n\\nGenerated by git-cliff"\n'));
  assert.ok(!saysGenerated('line\nline\nline\nline\nline\n// Generated by a late comment\n'), 'only the first lines count');
});

test('C116: a generated file that an entry lists is covered, one that no entry lists is an error', async () => {
  const covered = makeApp({
    'docs/generators.toml': REGISTRY,
    'apps/x/app/src-tauri/resources/THIRD_PARTY_NOTICES.md': '# Notices\n',
    'apps/x/Cargo.lock': '# This file is automatically @generated by Cargo.\n',
    'ui/projects/p/generated/a.ts': '// Generated from the Rust types. Do not edit.\n',
  });
  assert.deepEqual(await findingsOf('C116', covered), []);

  const bad = makeApp({
    'docs/generators.toml': REGISTRY,
    'apps/x/Cargo.lock': '# This file is automatically @generated by Cargo.\n',
    'apps/y/Cargo.lock': '# This file is automatically @generated by Cargo.\n', // lockfile of an unregistered workspace
    'apps/y/app/src-tauri/resources/THIRD_PARTY_NOTICES.md': '# Notices\n', // by name
    'ui/projects/p/other/b.ts': '// Generated by tool.mjs. Do not edit.\n', // by header, outside the listed folder
    'ui/projects/p/generated/ok.ts': '// Generated from the Rust types. Do not edit.\n',
    'crates/k/src/generated.rs': '//! The generated TypeScript of this crate, checked on every test run.\n', // hand-written, not flagged
    'apps/x/fuzz/Cargo.lock': '# This file is automatically @generated by Cargo.\n', // exempt: a fuzz target
  });
  const f = (await findingsOf('C116', bad)).filter((x) => x.severity === 'error');
  assert.deepEqual(f.map((x) => [x.file, x.severity]).sort(), [
    ['apps/y/Cargo.lock', 'error'],
    ['apps/y/app/src-tauri/resources/THIRD_PARTY_NOTICES.md', 'error'],
    ['ui/projects/p/other/b.ts', 'error'],
  ]);
  assert.match(f[0].fix, /docs\/generators\.toml/);
});

test('C116: an outputs glob that matches no file is a warning, and a registry without entries is a broken check', async () => {
  const dead = makeApp({ 'docs/generators.toml': REGISTRY });
  const f = await findingsOf('C116', dead);
  assert.deepEqual(f.map((x) => x.severity), ['warn', 'warn', 'warn']);
  assert.match(f[0].message, /matches no tracked file/);

  const empty = makeApp({ 'docs/generators.toml': 'version = 1\n' });
  const e = await findingsOf('C116', empty);
  assert.equal(e.length, 1);
  assert.equal(e[0].unwaivable, true);
  assert.equal(e[0].outcome, 'check-broken');
});

test('C116: a root without a registry reports nothing', async () => {
  assert.deepEqual(await findingsOf('C116', makeApp({ 'a.txt': 'x\n' })), []);
});

test('C116 does not flag its own source (its header describes the phrases without using them)', () => {
  const own = readFileSync(new URL('../src/checks/C116-generator-registry.mjs', import.meta.url), 'utf8');
  assert.equal(saysGenerated(own.slice(0, 600)), false);
});
