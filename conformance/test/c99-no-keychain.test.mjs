import assert from 'node:assert/strict';
import { test } from 'node:test';
import { manifestFindings, sourceFindings } from '../src/checks/C99-no-keychain.mjs';
import { findingsOf, makeApp } from './helpers.mjs';

// Layers 1 and 2 only: the graph layers have their own tests (c99-graph.test.mjs).
const OFF = { options: { graph: 'off' } };
const app = (deps) => `[package]\nname = "demo-app"\nversion = "0.1.0"\n\n${deps}`;
const lines = (found) => found.map((f) => [f.line, f.what]);

// Positive controls (ADR 0057 §3, ER-33): each fixture must be found, or the scan cannot see what it is for.
test('C99 manifests: every way a crate can name the Keychain is found', () => {
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[dependencies]\npaddock-secrets = { path = "x", features = ["keyring"] }\n'))), [[6, 'paddock-secrets/keyring on macOS']]);
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[dependencies.keyring]\nversion = "4.2"\n'))), [[5, 'keyring (only paddock-secrets may use it)']]);
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[target.\'cfg(windows)\'.dependencies]\nkeyring = "4.2"\n'))), [[6, 'keyring (only paddock-secrets may use it)']], 'the one door holds on Windows too');
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[dependencies]\nsecurity-framework = "3"\n'))), [[6, 'security-framework on macOS']]);
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[dependencies]\nobjc2-security = { version = "0.3", features = ["SecItem"] }\n'))), [[6, 'objc2-security on macOS']]);
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[dependencies]\nstore = { package = "apple-native-keyring-store", version = "1" }\n'))), [[6, 'apple-native-keyring-store (only paddock-secrets may use it)']], 'a renamed dependency');
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[features]\nsecure = ["paddock-secrets?/keyring"]\n'))), [[6, 'paddock-secrets/keyring on macOS']], 'a feature entry');
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[dependencies.paddock-secrets]\npath = "x"\nfeatures = ["keyring"]\n'))), [[7, 'paddock-secrets/keyring on macOS']], 'a header table with the feature in its body');
  assert.deepEqual(lines(manifestFindings('a/Cargo.toml', app('[workspace.dependencies]\nkeyring-core = "1"\n'))), [[6, 'keyring-core (only paddock-secrets may use it)']]);
});

test('C99 manifests: allowed off macOS, the exempt crates and the plain shared crate pass', () => {
  for (const cfg of ['not(target_os = "macos")', 'windows', 'target_os = "windows"', 'target_os = "linux"']) {
    assert.deepEqual(manifestFindings('a/Cargo.toml', app(`[target.'cfg(${cfg})'.dependencies]\npaddock-secrets = { path = "x", features = ["keyring"] }\n`)), [], cfg);
  }
  assert.deepEqual(manifestFindings('a/Cargo.toml', app('[target.x86_64-pc-windows-msvc.dependencies]\nsecurity-framework = "3"\n')), [], 'a Windows triple');
  assert.equal(manifestFindings('a/Cargo.toml', app('[target.aarch64-apple-darwin.dependencies]\nsecurity-framework = "3"\n')).length, 1, 'a macOS triple');
  assert.equal(manifestFindings('a/Cargo.toml', app('[target.\'cfg(unix)\'.dependencies]\npaddock-secrets = { path = "x", features = ["keyring"] }\n')).length, 1, 'unix includes macOS');
  assert.deepEqual(manifestFindings('a/Cargo.toml', app('[dependencies]\npaddock-secrets = { path = "x" }\nkeyring-like = "1"\n# keyring = "4.2"\n')), [], 'no feature, another crate, a comment');
  const shared = '[package]\nname = "paddock-secrets"\n\n[features]\nkeyring = ["dep:keyring"]\n\n[dependencies]\nkeyring = { version = "4.2", optional = true }\n';
  assert.deepEqual(manifestFindings('crates/paddock-secrets/Cargo.toml', shared), [], 'the one door itself');
  assert.deepEqual(manifestFindings('crates/paddock-workspace-hack/Cargo.toml', '[package]\nname = "paddock-workspace-hack"\n\n[target.aarch64-apple-darwin.dependencies]\nsecurity-framework-sys = { version = "2" }\n'), [], 'generated by hakari, no code');
});

test('C99 sources: Keychain symbols and security subcommands are found in code of every shipped kind', () => {
  assert.deepEqual(lines(sourceFindings('src/k.rs', 'extern "C" {\n    fn SecItemCopyMatching(q: *const c_void, r: *mut c_void) -> i32;\n}\n')), [[2, 'SecItemCopyMatching']]);
  assert.deepEqual(lines(sourceFindings('src/k.m', '#import <Security/Security.h>\nOSStatus s = SecItemCopyMatching(q, &r);\n')), [[2, 'SecItemCopyMatching']]);
  assert.deepEqual(lines(sourceFindings('src/k.rs', 'fn f() {\n    Command::new("/usr/bin/security").args(["find-generic-password", "-s", "X"]);\n}\n')), [[2, 'security find-generic-password']]);
  assert.deepEqual(lines(sourceFindings('app/src/k.ts', "run('security dump-keychain');\n")), [[1, 'security dump-keychain']]);
  assert.deepEqual(lines(sourceFindings('src/k.rs', 'let a = ["security", "export", "-k", "x"];\nunsafe { SecKeychainSetUserInteractionAllowed(0) };\n')), [[1, 'security export'], [2, 'SecKeychainSetUserInteractionAllowed']]);
  assert.deepEqual(lines(sourceFindings('src-tauri/capabilities/main.json', '{"permissions": [{"identifier": "shell:allow-execute", "allow": [{"name": "kc", "cmd": "security", "args": true}]}]}\n')), [[1, 'a shell scope that runs security']]);
});

