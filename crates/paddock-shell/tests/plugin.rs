fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Every permission file of the plugin: Tauri's per-command ones and the generated sets.
fn permission_files() -> Vec<PermissionFile> {
    let mut paths = vec![crate_dir().join("permissions/window-classes.toml")];
    let commands = crate_dir().join("permissions/autogenerated/commands");
    for e in std::fs::read_dir(commands).unwrap() {
        paths.push(e.unwrap().path());
    }
    paths
        .iter()
        .map(|p| toml::from_str(&std::fs::read_to_string(p).unwrap()).unwrap())
        .collect()
}

/// The app's capabilities as an app grants the shell: one set per window class.
fn capabilities(sets: &[(&str, &[&str], &str)]) -> BTreeMap<String, Capability> {
    sets.iter()
        .map(|(id, windows, permission)| {
            let c: Capability = serde_json::from_value(json!({
                "identifier": id,
                "windows": windows,
                "permissions": [permission],
            }))
            .unwrap();
            (id.to_string(), c)
        })
        .collect()
}

const CLASSES: [(&str, &[&str], &str); 4] = [
    ("main", &["main", "w-*"], "paddock-shell:default"),
    ("popout", &["p-*"], "paddock-shell:popout"),
    ("dialog", &["d-*"], "paddock-shell:dialog"),
    ("tray", &["tray", "tray-*"], "paddock-shell:tray"),
];

fn context() -> tauri::Context<MockRuntime> {
    let mut ctx = mock_context(noop_assets());
    let acl = BTreeMap::from([(
        PLUGIN_NAME.to_string(),
        Manifest::new(permission_files(), None),
    )]);
    let resolved = Resolved::resolve(
        &acl,
        capabilities(&CLASSES),
        tauri_utils::platform::Target::current(),
    )
    .unwrap();
    *ctx.runtime_authority_mut() = tauri::runtime_authority!(acl, resolved);
    ctx
}

fn identity() -> AppIdentity {
    AppIdentity::new("demo", "Shell Demo", "1.2.3")
}

fn app(builder: Builder<MockRuntime>) -> App<MockRuntime> {
    mock_builder()
        .plugin(builder.build())
        .build(context())
        .unwrap()
}

fn window(app: &App<MockRuntime>, label: &str) -> WebviewWindow<MockRuntime> {
    WebviewWindowBuilder::new(app, label, WebviewUrl::default())
        .build()
        .unwrap()
}

fn invoke(w: &WebviewWindow<MockRuntime>, cmd: &str, args: Value) -> Result<Value, Value> {
    let request = InvokeRequest {
        cmd: format!("plugin:{PLUGIN_NAME}|{cmd}"),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: if cfg!(windows) {
            "http://tauri.localhost"
        } else {
            "tauri://localhost"
        }
        .parse()
        .unwrap(),
        body: InvokeBody::Json(args),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    };
    get_ipc_response(w, request).map(|b| b.deserialize::<Value>().unwrap())
}

fn text(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// A label of each class (a dialog under `main`).
fn label_of(class: WindowClass) -> &'static str {
    match class {
        WindowClass::Main => "main",
        WindowClass::Popout => "p-main-1",
        WindowClass::Dialog => "d-main-1",
        WindowClass::Tray => "tray",
    }
}

/// Commands that would act on the test process itself (quit, restart); they are reached with a call that is refused
/// before they act (no arguments where they need some, or no state).
const SIDE_EFFECTS: [&str; 2] = ["app_quit", "updates_restart"];

#[test]
fn every_shell_command_is_registered_and_reaches_its_handler_from_a_window_it_is_open_to() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let windows: BTreeMap<&str, WebviewWindow<MockRuntime>> = WindowClass::ALL
        .iter()
        .map(|c| (label_of(*c), window(&app, label_of(*c))))
        .collect();
    assert!(
        COMMANDS.specs().len() >= 40,
        "the table holds every shell crate's commands"
    );
    for spec in COMMANDS.specs() {
        if SIDE_EFFECTS.contains(&spec.name()) {
            continue;
        }
        // From a window the table does not open it to the guard never runs: Tauri's ACL refuses first.
        let class = spec.windows().classes()[0];
        let w = &windows[label_of(class)];
        let answer = invoke(w, spec.name(), json!({}));
        let said = answer.as_ref().map_or_else(text, text);
        assert!(!said.contains("not found"), "{}: {said}", spec.name());
        assert!(
            !said.contains("not allowed"),
            "{} from {}: {said}",
            spec.name(),
            w.label()
        );
    }
}

#[test]
fn the_permission_sets_open_each_command_to_exactly_the_classes_of_the_table() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let windows: Vec<(WindowClass, WebviewWindow<MockRuntime>)> = WindowClass::ALL
        .iter()
        .map(|c| (*c, window(&app, label_of(*c))))
        .collect();
    for spec in COMMANDS.specs() {
        if SIDE_EFFECTS.contains(&spec.name()) {
            continue;
        }
        for (class, w) in &windows {
            let said = invoke(w, spec.name(), json!({})).map_or_else(|e| text(&e), |v| text(&v));
            let refused = said.contains("not allowed");
            assert_eq!(
                refused,
                !spec.windows().contains(*class),
                "{} from {}: {said}",
                spec.name(),
                w.label()
            );
        }
    }
    // A webview outside the label scheme has no capability at all.
    let stray = window(&app, "stray");
    assert!(text(&invoke(&stray, "shell_version", json!({})).unwrap_err()).contains("not allowed"));
}

#[test]
fn a_dialog_reaches_only_what_its_contract_declares() {
    let contracts = r#"{"version":1,"base":[],"dialogs":{"sd.settings":{"kind":"tool","modality":"modeless","requiredChoice":false,"instanced":false,"commands":["settings_overview"]}}}"#;
    let app = app(Builder::new(identity())
        .in_memory()
        .native_menu(false)
        .dialog_contracts(contracts));
    // The dialog layer does not know this window: the ACL lets the dialog set through, the guard refuses.
    let unknown = window(&app, "d-main-1");
    let e = invoke(&unknown, "settings_overview", json!({})).unwrap_err();
    assert_eq!(
        (e["code"].as_str(), e["command"].as_str()),
        (Some("denied"), Some("settings_overview")),
        "{e}"
    );
    assert!(text(&e["message"]).contains("unknown dialog"), "{e}");
}

