//! The plugin on Tauri's mock runtime (no window reaches the desktop, nothing is written outside temp folders): every
//! shell command is registered as `plugin:paddock-shell|<command>`, the generated permission sets resolve through
//! Tauri's own ACL per window class, the guard narrows dialogs to their contracts, and the shell's parts work through
//! the plugin (version, window notices to every window, update preferences on the settings).

use paddock_commands::WindowClass;
use paddock_shell::{AppIdentity, Builder, COMMANDS, PLUGIN_NAME, VERSION};
use paddock_updater::tauri::UpdatesBuilder;
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};
use tauri::ipc::{CallbackFn, InvokeBody};
use tauri::test::{
    INVOKE_KEY, MockRuntime, get_ipc_response, mock_builder, mock_context, noop_assets,
};
use tauri::webview::InvokeRequest;
use tauri::{App, Listener, WebviewUrl, WebviewWindow, WebviewWindowBuilder};
use tauri_utils::acl::capability::Capability;
use tauri_utils::acl::manifest::{Manifest, PermissionFile};
use tauri_utils::acl::resolved::Resolved;

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Every permission file of the plugin: Tauri's per-command ones and the generated sets.
fn permission_files() -> Vec<PermissionFile> {
    let mut paths = vec![crate_dir().join("permissions/window-classes.toml")];
    let commands = crate_dir().join("permissions/autogenerated/commands");
    for e in std::fs::read_dir(commands).unwrap() {
        paths.push(e.unwrap().path());
    }
    paths
        .iter()
        .map(|p| toml::from_str(&std::fs::read_to_string(p).unwrap()).unwrap())
        .collect()
}

/// The app's capabilities as an app grants the shell: one set per window class.
fn capabilities(sets: &[(&str, &[&str], &str)]) -> BTreeMap<String, Capability> {
    sets.iter()
        .map(|(id, windows, permission)| {
            let c: Capability = serde_json::from_value(json!({
                "identifier": id,
                "windows": windows,
                "permissions": [permission],
            }))
            .unwrap();
            (id.to_string(), c)
        })
        .collect()
}

const CLASSES: [(&str, &[&str], &str); 4] = [
    ("main", &["main", "w-*"], "paddock-shell:default"),
    ("popout", &["p-*"], "paddock-shell:popout"),
    ("dialog", &["d-*"], "paddock-shell:dialog"),
    ("tray", &["tray", "tray-*"], "paddock-shell:tray"),
];

fn context() -> tauri::Context<MockRuntime> {
    let mut ctx = mock_context(noop_assets());
    let acl = BTreeMap::from([(
        PLUGIN_NAME.to_string(),
        Manifest::new(permission_files(), None),
    )]);
    let resolved = Resolved::resolve(
        &acl,
        capabilities(&CLASSES),
        tauri_utils::platform::Target::current(),
    )
    .unwrap();
    *ctx.runtime_authority_mut() = tauri::runtime_authority!(acl, resolved);
    ctx
}

fn identity() -> AppIdentity {
    AppIdentity::new("demo", "Shell Demo", "1.2.3")
}

fn app(builder: Builder<MockRuntime>) -> App<MockRuntime> {
    mock_builder()
        .plugin(builder.build())
        .build(context())
        .unwrap()
}

fn window(app: &App<MockRuntime>, label: &str) -> WebviewWindow<MockRuntime> {
    WebviewWindowBuilder::new(app, label, WebviewUrl::default())
        .build()
        .unwrap()
}

fn invoke(w: &WebviewWindow<MockRuntime>, cmd: &str, args: Value) -> Result<Value, Value> {
    let request = InvokeRequest {
        cmd: format!("plugin:{PLUGIN_NAME}|{cmd}"),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: if cfg!(windows) {
            "http://tauri.localhost"
        } else {
            "tauri://localhost"
        }
        .parse()
        .unwrap(),
        body: InvokeBody::Json(args),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    };
    get_ipc_response(w, request).map(|b| b.deserialize::<Value>().unwrap())
}

fn text(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// A label of each class (a dialog under `main`).
fn label_of(class: WindowClass) -> &'static str {
    match class {
        WindowClass::Main => "main",
        WindowClass::Popout => "p-main-1",
        WindowClass::Dialog => "d-main-1",
        WindowClass::Tray => "tray",
    }
}

/// Commands that would act on the test process itself (quit, restart); they are reached with a call that is refused
/// before they act (no arguments where they need some, or no state).
const SIDE_EFFECTS: [&str; 2] = ["app_quit", "updates_restart"];

#[test]
fn every_shell_command_is_registered_and_reaches_its_handler_from_a_window_it_is_open_to() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let windows: BTreeMap<&str, WebviewWindow<MockRuntime>> = WindowClass::ALL
        .iter()
        .map(|c| (label_of(*c), window(&app, label_of(*c))))
        .collect();
    assert!(
        COMMANDS.specs().len() >= 40,
        "the table holds every shell crate's commands"
    );
    for spec in COMMANDS.specs() {
        if SIDE_EFFECTS.contains(&spec.name()) {
            continue;
        }
        // From a window the table does not open it to the guard never runs: Tauri's ACL refuses first.
        let class = spec.windows().classes()[0];
        let w = &windows[label_of(class)];
        let answer = invoke(w, spec.name(), json!({}));
        let said = answer.as_ref().map_or_else(text, text);
        assert!(!said.contains("not found"), "{}: {said}", spec.name());
        assert!(
            !said.contains("not allowed"),
            "{} from {}: {said}",
            spec.name(),
            w.label()
        );
    }
}

#[test]
fn the_permission_sets_open_each_command_to_exactly_the_classes_of_the_table() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let windows: Vec<(WindowClass, WebviewWindow<MockRuntime>)> = WindowClass::ALL
        .iter()
        .map(|c| (*c, window(&app, label_of(*c))))
        .collect();
    for spec in COMMANDS.specs() {
        if SIDE_EFFECTS.contains(&spec.name()) {
            continue;
        }
        for (class, w) in &windows {
            let said = invoke(w, spec.name(), json!({})).map_or_else(|e| text(&e), |v| text(&v));
            let refused = said.contains("not allowed");
            assert_eq!(
                refused,
                !spec.windows().contains(*class),
                "{} from {}: {said}",
                spec.name(),
                w.label()
            );
        }
    }
    // A webview outside the label scheme has no capability at all.
    let stray = window(&app, "stray");
    assert!(text(&invoke(&stray, "shell_version", json!({})).unwrap_err()).contains("not allowed"));
}

#[test]
fn a_dialog_reaches_only_what_its_contract_declares() {
    let contracts = r#"{"version":1,"base":[],"dialogs":{"sd.settings":{"kind":"tool","modality":"modeless","requiredChoice":false,"instanced":false,"commands":["settings_overview"]}}}"#;
    let app = app(Builder::new(identity())
        .in_memory()
        .native_menu(false)
        .dialog_contracts(contracts));
    // The dialog layer does not know this window: the ACL lets the dialog set through, the guard refuses.
    let unknown = window(&app, "d-main-1");
    let e = invoke(&unknown, "settings_overview", json!({})).unwrap_err();
    assert_eq!(
        (e["code"].as_str(), e["command"].as_str()),
        (Some("denied"), Some("settings_overview")),
        "{e}"
    );
    assert!(text(&e["message"]).contains("unknown dialog"), "{e}");
}

#[test]
fn shell_version_answers_the_crates_version_and_the_apps_identity() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let tray = window(&app, "tray");
    let v = invoke(&tray, "shell_version", json!({})).unwrap();
    assert_eq!(
        v,
        json!({ "shell": VERSION, "app": { "id": "demo", "name": "Shell Demo", "version": "1.2.3" } })
    );
}

/// The npm package's version, from its single source (rule 6).
fn npm_version() -> String {
    let path = crate_dir().join("../../ui/projects/paddock-ui/package.json");
    let pkg: Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    pkg["version"].as_str().unwrap().to_string()
}

#[test]
fn the_plugin_and_the_ui_package_carry_one_version() {
    let npm = npm_version();
    let parts: Vec<&str> = npm.split('.').collect();
    assert!(
        parts.len() == 3 && parts.iter().all(|p| p.parse::<u32>().is_ok()),
        "a release number: {npm}"
    );
    assert_eq!(
        VERSION, npm,
        "bump paddock-shell and @decryp7/paddock-ui together (ADR 0012 §3)"
    );
}

#[test]
fn a_window_notice_reaches_every_window_through_the_plugin() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let (main, second) = (window(&app, "main"), window(&app, "w-2"));
    let heard: Arc<Mutex<Vec<Value>>> = Arc::default();
    let h = heard.clone();
    second.listen("paddock://notifications", move |e| {
        h.lock()
            .unwrap()
            .push(serde_json::from_str(e.payload()).unwrap())
    });
    let posted = invoke(
        &main,
        "notifications_post",
        json!({ "notice": { "severity": "warning", "title": "Low disk" } }),
    )
    .unwrap();
    assert_eq!(posted["cause"], "ui:warning:Low disk");
    let heard = heard.lock().unwrap();
    assert_eq!(heard.len(), 1);
    assert_eq!(heard[0]["posted"]["title"], "Low disk");
    let list = invoke(&second, "notifications_list", json!({})).unwrap();
    assert_eq!(list["notices"][0]["title"], "Low disk");
}

fn updater_app(dir: &Path) -> App<MockRuntime> {
    let (config, cache) = (dir.join("config"), dir.join("cache"));
    app(Builder::new(identity())
        .in_memory()
        .native_menu(false)
        .updater(move |_| {
            UpdatesBuilder::new("Shell Demo")
                .channel("stable", "Stable", "https://example.invalid/stable.json")
                .channel("beta", "Beta", "https://example.invalid/beta.json")
                .dirs(config, cache)
                .background(false)
        }))
}

#[test]
fn the_update_preferences_live_on_the_settings_section() {
    let dir = tempfile::tempdir().unwrap();
    let app = updater_app(dir.path());
    let main = window(&app, "main");
    let section = |overview: &Value| {
        overview["sections"]
            .as_array()
            .unwrap()
            .iter()
            .find(|s| s["id"] == "pd.updates")
            .cloned()
            .unwrap()
    };
    let before = section(&invoke(&main, "settings_overview", json!({})).unwrap());
    assert_eq!(
        before["values"],
        json!({ "autoCheck": false, "channel": "stable" })
    );
    // The Updates dialog's command stores through the settings, and the updater follows.
    let status = invoke(
        &main,
        "updates_set_preferences",
        json!({ "preferences": { "autoCheck": true, "channel": "beta" } }),
    )
    .unwrap();
    assert_eq!(
        (status["autoCheck"].as_bool(), status["channel"].as_str()),
        (Some(true), Some("beta"))
    );
    let after = section(&invoke(&main, "settings_overview", json!({})).unwrap());
    assert_eq!(
        after["values"],
        json!({ "autoCheck": true, "channel": "beta" })
    );
    // A change in the Settings window reaches the updater the same way.
    let set = invoke(
        &main,
        "settings_set",
        json!({ "section": "pd.updates", "values": { "channel": "stable" } }),
    )
    .unwrap();
    assert_eq!(set["applied"], true, "{set}");
    let status = invoke(&main, "updates_status", json!({})).unwrap();
    assert_eq!(
        (status["autoCheck"].as_bool(), status["channel"].as_str()),
        (Some(true), Some("stable"))
    );
    // An unknown channel is refused by the settings' own validation, and nothing changes.
    let bad = invoke(
        &main,
        "updates_set_preferences",
        json!({ "preferences": { "autoCheck": false, "channel": "nightly" } }),
    );
    assert!(bad.is_err());
    let status = invoke(&main, "updates_status", json!({})).unwrap();
    assert_eq!(status["channel"], "stable");
    // Only the updater's own files are written, in the folders it was given.
    assert!(
        !dir.path().join("config").join("settings.json").exists(),
        "settings stay in memory"
    );
}
