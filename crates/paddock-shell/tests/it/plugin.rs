#[test]
fn a_window_notice_reaches_every_window_through_the_plugin() {
    let app = app(Builder::new(identity()).in_memory().native_menu(false));
    let (main, second) = (window(&app, "main"), window(&app, "w-2"));
    let heard: Arc<Mutex<Vec<Value>>> = Arc::default();
    let h = heard.clone();
    second.listen("paddock://notifications", move |e| {
        h.lock()
            .unwrap()
            .push(serde_json::from_str(e.payload()).unwrap())
    });
    let posted = invoke(
        &main,
        "notifications_post",
        json!({ "notice": { "severity": "warning", "title": "Low disk" } }),
    )
    .unwrap();
    assert_eq!(posted["cause"], "ui:warning:Low disk");
    let heard = heard.lock().unwrap();
    assert_eq!(heard.len(), 1);
    assert_eq!(heard[0]["posted"]["title"], "Low disk");
    let list = invoke(&second, "notifications_list", json!({})).unwrap();
    assert_eq!(list["notices"][0]["title"], "Low disk");
}

