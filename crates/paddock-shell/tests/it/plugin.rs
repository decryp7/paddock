#[test]
fn the_update_preferences_live_on_the_settings_section() {
    let dir = tempfile::tempdir().unwrap();
    let app = updater_app(dir.path());
    let main = window(&app, "main");
    let section = |overview: &Value| {
        overview["sections"]
            .as_array()
            .unwrap()
            .iter()
            .find(|s| s["id"] == "pd.updates")
            .cloned()
            .unwrap()
    };
    let before = section(&invoke(&main, "settings_overview", json!({})).unwrap());
    assert_eq!(
        before["values"],
        json!({ "autoCheck": false, "channel": "stable" })
    );
    // The Updates dialog's command stores through the settings, and the updater follows.
    let status = invoke(
        &main,
        "updates_set_preferences",
        json!({ "preferences": { "autoCheck": true, "channel": "beta" } }),
    )
    .unwrap();
    assert_eq!(
        (status["autoCheck"].as_bool(), status["channel"].as_str()),
        (Some(true), Some("beta"))
    );
    let after = section(&invoke(&main, "settings_overview", json!({})).unwrap());
    assert_eq!(
        after["values"],
        json!({ "autoCheck": true, "channel": "beta" })
    );
    // A change in the Settings window reaches the updater the same way.
    let set = invoke(
        &main,
        "settings_set",
        json!({ "section": "pd.updates", "values": { "channel": "stable" } }),
    )
    .unwrap();
    assert_eq!(set["applied"], true, "{set}");
    let status = invoke(&main, "updates_status", json!({})).unwrap();
    assert_eq!(
        (status["autoCheck"].as_bool(), status["channel"].as_str()),
        (Some(true), Some("stable"))
    );
    // An unknown channel is refused by the settings' own validation, and nothing changes.
    let bad = invoke(
        &main,
        "updates_set_preferences",
        json!({ "preferences": { "autoCheck": false, "channel": "nightly" } }),
    );
    assert!(bad.is_err());
    let status = invoke(&main, "updates_status", json!({})).unwrap();
    assert_eq!(status["channel"], "stable");
    // Only the updater's own files are written, in the folders it was given.
    assert!(
        !dir.path().join("config").join("settings.json").exists(),
        "settings stay in memory"
    );
}

#[test]
fn every_part_is_set_up_in_order_and_the_apps_setup_runs_last() {
    use paddock_window::tauri::{WindowConfig, Windows};
    use std::sync::atomic::{AtomicUsize, Ordering};
    let order = Arc::new(AtomicUsize::new(0));
    let (seen_health, seen_setup) = (order.clone(), order.clone());
    let startup = paddock_startup::tauri::Startup::builder().build().unwrap();
    let app = app(Builder::new(identity())
        .in_memory()
        .native_menu(false)
        .health(vec![paddock_health::ServiceSpec::new(
            "sd.engine",
            "the engine",
        )])
        .health_setup(move |_, setup| {
            seen_health.fetch_add(1, Ordering::SeqCst);
            setup
        })
        .settings(|_| paddock_settings::Settings::in_memory())
        .startup(startup)
        .windows(|_| Windows::builder(WindowConfig::new("Shell Demo")).build())
        .downloader(paddock_download::Downloader::http(Default::default()).unwrap())
        .setup(move |app| {
            // The shell's state is there when the app's own set-up runs.
            assert!(
                app.try_state::<paddock_settings::tauri::ManagedSettings>()
                    .is_some()
            );
            seen_setup.fetch_add(10, Ordering::SeqCst);
            Ok(())
        }));
    assert_eq!(
        order.load(Ordering::SeqCst),
        11,
        "the health adjustment and the app's set-up both ran"
    );
    let main = window(&app, "main");
    let health = invoke(&main, "health_snapshot", json!({})).unwrap();
    assert_eq!(health["services"][0]["service"], "sd.engine");
    let windows = invoke(&main, "windows_list", json!({})).unwrap();
    assert!(windows.is_array(), "the window layer answers: {windows}");
    drop(app);
}

