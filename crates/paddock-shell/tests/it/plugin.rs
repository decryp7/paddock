//! The plugin on Tauri's mock runtime (no window reaches the desktop, nothing is written outside temp folders): every
//! shell command is registered as `plugin:paddock-shell|<command>`, the generated permission sets resolve through
//! Tauri's own ACL per window class, the guard narrows dialogs to their contracts, and the shell's parts work through
//! the plugin (version, window notices to every window, update preferences on the settings).

