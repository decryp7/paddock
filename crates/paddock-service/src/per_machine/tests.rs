/// A silent run must tell a refusal from NSIS's own endings (1 cancelled, 2 aborted) and from apply-update's codes (20 up), and
/// the reason must reach the protected log without the elevated installer writing a path of its own.
#[test]
fn refusals_have_their_own_exit_levels_and_note_into_the_protected_log() {
    let t = canonical_include();
    let lines: Vec<&str> = t.lines().map(str::trim_end).collect();
    for (name, n) in [
        ("PER_USER", 40),
        ("BAD_DIR", 41),
        ("STILL_RUNNING", 42),
        ("TOOL_FAILED", 43),
    ] {
        let want = format!("!define PADDOCK_LEVEL_{name} {n}");
        assert!(
            lines.contains(&want.as_str()),
            "{name} is {n} (compared over lines, CRLF or not)"
        );
    }
    assert!(
        t.contains(" note --dir "),
        "the reason goes through paddock-setup note"
    );
    // The only FileOpen is the test harness's log line (compiled only with PADDOCK_TEST_HARNESS).
    let opens: Vec<usize> = t.match_indices("FileOpen").map(|(i, _)| i).collect();
    assert_eq!(opens.len(), 1, "one FileOpen");
    let before = &t[..opens[0]];
    let macro_start = before.rfind("!macro").unwrap();
    assert!(
        before[macro_start..].contains("!ifdef PADDOCK_TEST_HARNESS"),
        "and it is the harness's"
    );
    assert!(
        !t.contains("$TEMP"),
        "nothing is written under %TEMP% while elevated"
    );
}

/// The uninstaller's last step retries a Delete that lost to a transient lock, never recurses, never registers a restart and
/// never raises the reboot flag (a restart would delete the uninstall.exe of a reinstall made before it).
#[test]
fn the_uninstall_finish_retries_without_recursion_or_reboot_flags() {
    let t = canonical_include();
    let code: Vec<&str> = t
        .lines()
        .filter(|l| !l.trim_start().starts_with(';'))
        .collect();
    let start = code
        .iter()
        .position(|l| l.contains("!macro PADDOCK_FINISH_UNINSTALL"))
        .expect("the macro exists");
    let end = start
        + code[start..]
            .iter()
            .position(|l| l.contains("!macroend"))
            .unwrap();
    let body = code[start..=end].join("\n");
    assert!(
        body.contains("${While}")
            && body.contains("Delete \"$INSTDIR\\uninstall.exe\"")
            && body.contains("Sleep 100"),
        "a bounded retry"
    );
    assert!(body.contains("$R4 >= 50"), "bounded: 50 tries of 100 ms");
    assert!(
        body.contains("RMDir \"$INSTDIR\"") && !body.contains("/r"),
        "RMDir only, never recursive"
    );
    assert!(
        !body.contains("REBOOTOK") && !body.contains("SetRebootFlag"),
        "no restart registration, no flag"
    );
    assert!(
        body.contains("CreateFileW") && body.contains("RmGetList"),
        "the cause is recorded: an exclusive open and Restart Manager"
    );
    for outcome in [
        "removed",
        "removed-after-retries",
        "kept-other-files",
        "left-in-place",
    ] {
        assert!(body.contains(outcome), "{outcome}");
    }
}
