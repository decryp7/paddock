#[test]
fn bad_input_is_refused() {
    assert_eq!(
        stop_images(" ", &[], &[]),
        Err(PerMachineError::NoMainBinary)
    );
    for bad in [
        "a,b",
        "a\"b",
        "a$b",
        "-x",
        "a/../b\\..\\",
        "a;b",
        "a/",
        "",
        "..",
        "x y/",
        "C:\\",
    ] {
        let r = stop_images("m", &s(&[bad]), &[]);
        assert!(
            matches!(r, Err(PerMachineError::BadName(_))),
            "{bad:?} must be refused, not shortened to a name: {r:?}"
        );
    }
    assert!(matches!(
        stop_images("a,b", &[], &[]),
        Err(PerMachineError::BadName(_))
    ));
    assert!(matches!(
        stop_images("m", &s(&["x\"y"]), &[]),
        Err(PerMachineError::BadName(_))
    ));
    assert!(matches!(
        stop_images("-m", &[], &[]),
        Err(PerMachineError::BadName(_))
    ));
    assert_eq!(
        stop_images("m", &[], &[ex("m.exe", "  ")]),
        Err(PerMachineError::NoReason("m.exe".into()))
    );
    assert_eq!(
        stop_images("m", &[], &[ex("gone.exe", "why")]),
        Err(PerMachineError::UnknownExclusion("gone.exe".into()))
    );
    for e in [
        PerMachineError::NoSurvivalStatement("x".into()),
        PerMachineError::NoMainBinary,
        PerMachineError::BadName("x".into()),
        PerMachineError::NoReason("x".into()),
        PerMachineError::UnknownExclusion("x".into()),
    ] {
        assert!(!e.to_string().is_empty());
    }
}

