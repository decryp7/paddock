fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Every permission file of the plugin: Tauri's per-command ones and the generated sets.
fn permission_files() -> Vec<PermissionFile> {
    let mut paths = vec![crate_dir().join("permissions/window-classes.toml")];
    for e in std::fs::read_dir(crate_dir().join("permissions/autogenerated/commands")).unwrap() {
        paths.push(e.unwrap().path());
    }
    paths
        .iter()
        .map(|p| toml::from_str(&std::fs::read_to_string(p).unwrap()).unwrap())
        .collect()
}

/// The app's capabilities as an app grants the workbench: one set per window class.
const CLASSES: [(&str, &[&str], &str); 3] = [
    ("main", &["main", "w-*"], "paddock-workbench:default"),
    ("popout", &["p-*"], "paddock-workbench:popout"),
    ("dialog", &["d-*"], "paddock-workbench:dialog"),
];

fn context() -> tauri::Context<MockRuntime> {
    let mut ctx = mock_context(noop_assets());
    let acl = BTreeMap::from([(
        PLUGIN_NAME.to_string(),
        Manifest::new(permission_files(), None),
    )]);
    let capabilities: BTreeMap<String, Capability> = CLASSES
        .iter()
        .map(|(id, windows, permission)| {
            let c: Capability = serde_json::from_value(
                json!({ "identifier": id, "windows": windows, "permissions": [permission] }),
            )
            .unwrap();
            (id.to_string(), c)
        })
        .collect();
    let resolved =
        Resolved::resolve(&acl, capabilities, tauri_utils::platform::Target::current()).unwrap();
    *ctx.runtime_authority_mut() = tauri::runtime_authority!(acl, resolved);
    ctx
}

/// A provider that answers every turn with one canned reply.
struct Canned;

impl LlmProvider for Canned {
    fn id(&self) -> &str {
        "canned"
    }
    fn display_name(&self) -> String {
        "Canned".into()
    }
    fn context_length(&self) -> usize {
        8192
    }
    fn chat(
        &self,
        _: &ChatRequest,
        on_delta: &mut dyn FnMut(&str),
    ) -> Result<ChatResponse, ProviderError> {
        on_delta("ok");
        Ok(ChatResponse {
            text: "ok".into(),
            tool_calls: vec![],
            stop_reason: StopReason::EndTurn,
            usage: None,
        })
    }
}

fn assistant(dir: &std::path::Path) -> Arc<Assistant> {
    let clock = FakeClock::at_wall_ms(1_700_000_000_000);
    let store = Arc::new(ConversationStore::open(
        dir.join("assistant.json"),
        Arc::new(clock.clone()),
    ));
    Assistant::new(
        Arc::new(Canned),
        Tools::new(vec![]).unwrap(),
        store,
        Arc::new(clock) as Arc<dyn Clock>,
        AssistantConfig::new("Demo", "You are the demo assistant."),
    )
}

fn full(dir: &std::path::Path) -> Builder<MockRuntime> {
    Builder::new()
        .layouts(dir)
        .panels(Panels::builder().build())
        .assistant(assistant(dir))
}

fn app(builder: Builder<MockRuntime>) -> App<MockRuntime> {
    mock_builder()
        .plugin(builder.build())
        .build(context())
        .unwrap()
}

fn window(app: &App<MockRuntime>, label: &str) -> WebviewWindow<MockRuntime> {
    WebviewWindowBuilder::new(app, label, WebviewUrl::default())
        .build()
        .unwrap()
}

fn invoke(w: &WebviewWindow<MockRuntime>, cmd: &str, args: Value) -> Result<Value, Value> {
    let request = InvokeRequest {
        cmd: format!("plugin:{PLUGIN_NAME}|{cmd}"),
        callback: CallbackFn(0),
        error: CallbackFn(1),
        url: if cfg!(windows) {
            "http://tauri.localhost"
        } else {
            "tauri://localhost"
        }
        .parse()
        .unwrap(),
        body: InvokeBody::Json(args),
        headers: Default::default(),
        invoke_key: INVOKE_KEY.to_string(),
    };
    get_ipc_response(w, request).map(|b| b.deserialize::<Value>().unwrap())
}

fn text(v: &Value) -> String {
    match v {
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// A label of each class (a dialog under `main`).
fn label_of(class: WindowClass) -> &'static str {
    match class {
        WindowClass::Main => "main",
        WindowClass::Popout => "p-main-1",
        WindowClass::Dialog => "d-main-1",
        WindowClass::Tray => "tray",
    }
}

/// The classes the plugin serves (the workbench has no tray commands).
fn classes() -> Vec<WindowClass> {
    WindowClass::ALL
        .iter()
        .copied()
        .filter(|c| *c != WindowClass::Tray)
        .collect()
}

#[test]
fn every_command_is_registered_and_reaches_its_handler_from_a_window_it_is_open_to() {
    let dir = tempfile::tempdir().unwrap();
    let app = app(full(dir.path()));
    let windows: BTreeMap<&str, WebviewWindow<MockRuntime>> = classes()
        .iter()
        .map(|c| (label_of(*c), window(&app, label_of(*c))))
        .collect();
    assert!(
        COMMANDS.specs().len() >= 19,
        "layout, panels and assistant commands"
    );
    for spec in COMMANDS.specs() {
        let w = &windows[label_of(spec.windows().classes()[0])];
        let said = invoke(w, spec.name(), json!({})).map_or_else(|e| text(&e), |v| text(&v));
        assert!(!said.contains("not found"), "{}: {said}", spec.name());
        assert!(
            !said.contains("not allowed"),
            "{} from {}: {said}",
            spec.name(),
            w.label()
        );
    }
}

#[test]
fn the_permission_sets_open_each_command_to_exactly_the_classes_of_the_table() {
    let dir = tempfile::tempdir().unwrap();
    let app = app(full(dir.path()));
    let windows: Vec<(WindowClass, WebviewWindow<MockRuntime>)> = classes()
        .iter()
        .map(|c| (*c, window(&app, label_of(*c))))
        .collect();
    for spec in COMMANDS.specs() {
        for (class, w) in &windows {
            let said = invoke(w, spec.name(), json!({})).map_or_else(|e| text(&e), |v| text(&v));
            assert_eq!(
                said.contains("not allowed"),
                !spec.windows().contains(*class),
                "{} from {}: {said}",
                spec.name(),
                w.label()
            );
        }
    }
    // A webview outside the label scheme has no capability at all.
    let stray = window(&app, "stray");
    assert!(
        text(&invoke(&stray, "layout_get", json!({ "key": "main" })).unwrap_err())
            .contains("not allowed")
    );
}

#[test]
fn the_drag_ghost_window_matches_no_permission_set() {
    for (_, windows, _) in CLASSES {
        for pattern in windows {
            let prefix = pattern.trim_end_matches('*');
            let matches = if pattern.ends_with('*') {
                GHOST_LABEL.starts_with(prefix)
            } else {
                GHOST_LABEL == *pattern
            };
            assert!(!matches, "{GHOST_LABEL} matches {pattern}");
        }
    }
    let dir = tempfile::tempdir().unwrap();
    let app = app(full(dir.path()));
    let ghost = window(&app, GHOST_LABEL);
    for spec in COMMANDS.specs() {
        let said = invoke(&ghost, spec.name(), json!({})).map_or_else(|e| text(&e), |v| text(&v));
        assert!(
            said.contains("not allowed"),
            "{} from the ghost: {said}",
            spec.name()
        );
    }
}

#[test]
fn a_dialog_reaches_only_what_its_contract_declares() {
    let dir = tempfile::tempdir().unwrap();
    let app = app(full(dir.path()));
    let contracts = r#"{"version":1,"base":[],"dialogs":{"wb.tool":{"kind":"tool","modality":"modeless","requiredChoice":false,"instanced":false,"commands":[]}}}"#;
    app.manage(Dialogs::from_json(contracts).unwrap());
    // The dialog layer does not know this window: the ACL lets the dialog set through, the guard refuses.
    let unknown = window(&app, "d-main-1");
    let e = invoke(&unknown, "ui_sync_publish", json!({})).unwrap_err();
    assert_eq!(
        (e["code"].as_str(), e["command"].as_str()),
        (Some("denied"), Some("ui_sync_publish")),
        "{e}"
    );
    assert!(text(&e["message"]).contains("unknown dialog"), "{e}");
}

#[test]
fn layouts_are_saved_through_the_plugin_and_a_pop_out_reads_them() {
    let dir = tempfile::tempdir().unwrap();
    let app = app(full(dir.path()));
    let (main, popout) = (window(&app, "main"), window(&app, "p-main-1"));
    invoke(
        &main,
        "layout_set",
        json!({ "key": "main", "value": { "version": 1 } }),
    )
    .unwrap();
    assert_eq!(
        invoke(&popout, "layout_get", json!({ "key": "main" })).unwrap(),
        json!({ "version": 1 })
    );
    assert!(dir.path().join("workbench-layout.json").exists());
    assert!(
        text(
            &invoke(
                &popout,
                "layout_set",
                json!({ "key": "main", "value": null })
            )
            .unwrap_err()
        )
        .contains("not allowed")
    );
}

#[test]
fn the_assistant_answers_through_the_plugin_from_a_window_and_a_pop_out() {
    let dir = tempfile::tempdir().unwrap();
    let app = app(full(dir.path()));
    let (main, popout) = (window(&app, "main"), window(&app, "p-main-1"));
    let info = invoke(&main, "assistant_info", json!({})).unwrap();
    assert_eq!(info["provider"], "Canned", "{info}");
    assert!(
        invoke(&popout, "assistant_conversations", json!({}))
            .unwrap()
            .as_array()
            .unwrap()
            .is_empty()
    );
}

#[test]
fn a_part_the_app_leaves_out_answers_that_it_is_not_set_up() {
    let app = app(Builder::new());
    let main = window(&app, "main");
    for (cmd, args) in [
        ("layout_get", json!({ "key": "main" })),
        ("assistant_info", json!({})),
        ("panels_list", json!({})),
    ] {
        let e = invoke(&main, cmd, args);
        let said = e.map_or_else(|e| text(&e), |v| text(&v));
        assert!(
            !said.contains("not allowed") && !said.contains("not found"),
            "{cmd}: {said}"
        );
    }
    let e = invoke(&main, "layout_get", json!({ "key": "main" })).unwrap_err();
    assert!(text(&e["message"]).contains("not set up"), "{e}");
}

#[test]
fn a_pop_out_is_built_through_the_window_hooks() {
    let dir = tempfile::tempdir().unwrap();
    let built = Arc::new(AtomicUsize::new(0));
    let b = built.clone();
    let hooks = WindowHooks::new().built(move |_| {
        b.fetch_add(1, Ordering::SeqCst);
    });
    let app = app(full(dir.path()).window_hooks(hooks));
    let main = window(&app, "main");
    let info = invoke(
        &main,
        "panel_pop_out",
        json!({ "request": { "panel": "pn.code" } }),
    )
    .unwrap();
    assert_eq!(info["label"], "p-main-1", "{info}");
    assert_eq!(built.load(Ordering::SeqCst), 1);
    assert_eq!(
        invoke(&main, "panels_list", json!({}))
            .unwrap()
            .as_array()
            .unwrap()
            .len(),
        1
    );
}
