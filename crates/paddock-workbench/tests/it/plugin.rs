//! The plugin on Tauri's mock runtime (no window reaches the desktop, nothing is written outside temp folders): every
//! workbench command is registered as `plugin:paddock-workbench|<command>`, the generated permission sets resolve through
//! Tauri's own ACL per window class, the guard narrows dialogs to their contracts, and the parts work through the plugin.

