//! The TypeScript declarations the apps generate from: counts are `number`, wrappers are named like the wire.

use ts_rs::TS;

#[test]
fn declarations_use_number_for_counts_and_the_wire_names() {
    let quantity = crate::Quantity::decl();
    assert!(
        quantity.contains("number") && !quantity.contains("bigint"),
        "{quantity}"
    );
    let total = crate::Total::decl();
    assert!(
        total.contains("\"kind\": \"exact\"")
            && total.contains("number")
            && !total.contains("bigint"),
        "{total}"
    );
    let selection = crate::Selection::decl();
    assert!(
        selection.contains("\"kind\": \"topBy\"") && !selection.contains("bigint"),
        "{selection}"
    );
    let cut = crate::CutWire::decl();
    assert!(cut.starts_with("type Cut = "), "{cut}");
    assert!(
        cut.contains("limit: LimitId") && cut.contains("of: FieldPath") && !cut.contains("bigint"),
        "{cut}"
    );
    let bounded = crate::BoundedWire::<()>::decl();
    assert!(
        bounded.contains("type Bounded<T>") && bounded.contains("cuts: Array<Cut>"),
        "{bounded}"
    );
    assert!(
        crate::Limit::inline().contains("number") && crate::Buckets::inline().contains("number")
    );
    assert_eq!(crate::LimitId::decl(), "type LimitId = string;");
    assert_eq!(crate::SettingPath::decl(), "type SettingPath = string;");
    assert_eq!(crate::FieldPath::decl(), "type FieldPath = string;");
    assert!(crate::LimitExceeded::decl().contains("reached: Quantity | null"));
}

/// The hand-written declarations of the string and number newtypes answer every part of the trait the same way.
#[test]
fn the_newtype_declarations_agree_in_every_form() {
    fn all<T: TS>() -> [String; 5] {
        [
            T::name(),
            T::inline(),
            T::inline_flattened(),
            T::decl(),
            T::decl_concrete(),
        ]
    }
    for (parts, ty, name) in [
        (all::<crate::LimitId>(), "string", "LimitId"),
        (all::<crate::SettingPath>(), "string", "SettingPath"),
        (all::<crate::FieldPath>(), "string", "FieldPath"),
        (all::<crate::Limit>(), "number", "Limit"),
        (all::<crate::Buckets>(), "number", "Buckets"),
    ] {
        assert_eq!(parts[0], name);
        assert_eq!(parts[1], ty);
        assert_eq!(parts[2], ty);
        assert_eq!(parts[3], format!("type {name} = {ty};"));
        assert_eq!(parts[4], parts[3]);
    }
}

/// Review P1-2: a struct that holds a `Bounded` and a `Cut` can derive `TS`.
#[test]
fn a_struct_holding_bounded_and_cut_derives_ts() {
    #[derive(TS)]
    #[allow(dead_code)]
    struct Holder {
        rows: crate::Bounded<Vec<u32>>,
        one: crate::Cut,
    }
    let decl = Holder::decl();
    assert!(
        decl.contains("rows: Bounded<Array<number>>") && decl.contains("one: Cut"),
        "{decl}"
    );
}

/// Every declaration of the wire, in one text that is compared with the golden file (`PADDOCK_WRITE_TS=1` rewrites it): a
/// changed field, tag or number type shows as a diff, not as a failed substring.
fn declarations() -> String {
    let mut out = String::from(
        "// Generated by `PADDOCK_WRITE_TS=1 cargo test -p paddock-limits --features ts ts_tests`; do not edit.\n",
    );
    for decl in [
        crate::Unit::decl(),
        crate::Quantity::decl(),
        crate::Scope::decl(),
        crate::LimitId::decl(),
        crate::SettingPath::decl(),
        crate::FieldPath::decl(),
        crate::Total::decl(),
        crate::Order::decl(),
        crate::SortKey::decl(),
        crate::Selection::decl(),
        crate::Next::decl(),
        crate::CutWire::decl(),
        crate::BoundedWire::<()>::decl(),
        crate::LimitExceeded::decl(),
        crate::Limit::decl(),
        crate::Buckets::decl(),
        crate::Page::decl(),
        crate::Remedy::decl(),
        crate::RowValue::decl(),
        crate::RowKind::decl(),
        crate::SelectionKind::decl(),
        crate::LimitRow::decl(),
    ] {
        out.push_str(&decl);
        out.push('\n');
    }
    out
}

/// Equal up to line endings: a Windows checkout may convert the golden file to CRLF.
fn same_text(a: &str, b: &str) -> bool {
    a.replace("\r\n", "\n") == b.replace("\r\n", "\n")
}

#[test]
fn a_crlf_checkout_of_the_golden_file_still_matches() {
    let now = declarations();
    let crlf = now.replace('\n', "\r\n");
    assert_ne!(crlf, now);
    assert!(same_text(&crlf, &now));
    assert!(!same_text(&crlf, &format!("{now}x")));
}

#[test]
fn the_declarations_are_the_golden_file() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/golden/limits.ts");
    let now = declarations();
    if std::env::var_os("PADDOCK_WRITE_TS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &now).unwrap();
    }
    let golden = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        same_text(&golden, &now),
        "{} is stale: regenerate with PADDOCK_WRITE_TS=1 cargo test -p paddock-limits --features ts ts_tests",
        path.display()
    );
}

/// `Bounded<T>` and `Cut` declare themselves as the wire types they cross as.
#[test]
fn bounded_and_cut_delegate_every_part_of_the_declaration() {
    assert_eq!(crate::Cut::name(), crate::CutWire::name());
    assert_eq!(crate::Cut::ident(), crate::CutWire::ident());
    assert_eq!(crate::Cut::inline(), crate::CutWire::inline());
    assert_eq!(
        crate::Cut::inline_flattened(),
        crate::CutWire::inline_flattened()
    );
    assert_eq!(crate::Cut::decl(), crate::CutWire::decl());
    assert_eq!(crate::Cut::decl_concrete(), crate::CutWire::decl_concrete());
    type B = crate::Bounded<Vec<u32>>;
    type W = crate::BoundedWire<Vec<u32>>;
    assert_eq!(B::name(), W::name());
    assert_eq!(B::ident(), W::ident());
    assert_eq!(B::inline(), W::inline());
    assert_eq!(B::inline_flattened(), W::inline_flattened());
    assert_eq!(B::decl(), W::decl());
    assert_eq!(B::decl_concrete(), W::decl_concrete());
    assert_eq!(B::dependencies().len(), W::dependencies().len());
    struct Count(usize);
    impl ts_rs::TypeVisitor for Count {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            self.0 += 1;
        }
    }
    let (mut b, mut w) = (Count(0), Count(0));
    B::visit_generics(&mut b);
    W::visit_generics(&mut w);
    crate::Cut::visit_generics(&mut b);
    assert_eq!(b.0, w.0);
}
