import type { ShellCommand } from '../generated/shell-commands';

/**
 * Types an app plugs into the shell once, by module augmentation, so every `define*` is checked against them:
 *
 * ```ts
 * // src/app/shell-types.d.ts (or any file the app compiles)
 * import type { AppCommand } from './core/generated/app-commands'; // written by paddock-commands (plan S1)
 * declare module '@decryp7/paddock-ui/shell' {
 *   interface ShellTypes {
 *     appCommand: AppCommand;
 *   }
 * }
 * ```
 *
 * Without the augmentation the app's names fall back to `string`, so nothing changes for an app until it adds it.
 */
// eslint-disable-next-line @typescript-eslint/no-empty-object-type
export interface ShellTypes {}

/** The app's IPC command names: its generated `AppCommand` union once registered in `ShellTypes.appCommand`, else `string`. */
export type AppCommandName = ShellTypes extends { appCommand: infer C extends string } ? C : string;

/**
 * An IPC command a window may call: the app's table plus the shell plugin's (`ShellCommand`, generated by
 * `paddock-commands` into `shell/generated/shell-commands.ts`). Dialog contracts list these (crates/README.md).
 */
export type IpcCommandName = AppCommandName | ShellCommand;

/** A type carried at compile time only: `type<ModelInfo>()` states a dialog's result without a value. */
export interface TypeToken<T> {
  readonly __type?: T;
}

/** The compile-time token of `T` (an empty object at run time). */
export function type<T>(): TypeToken<T> {
  return {};
}

/**
 * What a dialog's opener receives when it is gone (ADR 0026 §2): never an ambiguous `undefined`. An answer of
 * `undefined` is a value like any other; the dismiss action, Escape, Cmd/Ctrl+W or an OS close are a dismissal.
 */
export type DialogOutcome<R> = { readonly kind: 'answered'; readonly value: R } | { readonly kind: 'dismissed' };

/** The outcome of a dismissed dialog. */
export const DISMISSED: DialogOutcome<never> = Object.freeze({ kind: 'dismissed' });

/** The outcome of a dialog answered with `value`. */
export function answered<R>(value: R): DialogOutcome<R> {
  return { kind: 'answered', value };
}

/** The value of an answered outcome, `undefined` for a dismissal (for an opener that only cares about the value). */
export function answerOf<R>(outcome: DialogOutcome<R>): R | undefined {
  return outcome.kind === 'answered' ? outcome.value : undefined;
}
