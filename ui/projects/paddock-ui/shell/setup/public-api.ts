/**
 * `@decryp7/paddock-ui/shell/setup`: the first-run set-up checklist (plan X19) over `paddock_shell::setup` (`setup_state`,
 * `setup_act`, `setup_repair`, `setup_skip`, `setup_finish`, changes on `paddock://setup`): the `SetupBackend` port (Tauri, and
 * in-memory), the per-window store, the Set-up window (a modeless `tool` dialog) and the Set-up page of the Settings window.
 *
 * The steps are the engine's: the background service, Start at login, notification permission, Pitwall pairing, and the
 * app's own (Debrief's tour). Each is skippable, a step with a problem always has a Repair that does not depend on the thing
 * it repairs (rule 19), and the checklist stays reachable from Settings and Help > Set-up… after it is finished.
 *
 * The window and the page (`PdSetupDialog`, `PdSetupPage`) are in `@decryp7/paddock-ui/shell/setup/page`, a chunk of their
 * own that only those windows load.
 *
 * ```ts
 * const SETUP = defineSetup({
 *   providers: () => import('./setup.providers').then((m) => m.SETUP_PROVIDERS),
 *   loadPage: () => import('@decryp7/paddock-ui/shell/setup/page').then((m) => m.PdSetupPage),
 *   loadDialog: () => import('@decryp7/paddock-ui/shell/setup/page').then((m) => m.PdSetupDialog),
 * });
 * // the registry: provideContributions(SETUP_CONTRIBUTIONS), and the app lists SETUP.dialog among its dialogs and SETUP.page among its settings pages; the Settings dialog's contract gains SETUP_DIALOG_COMMANDS
 * // setup.providers.ts: export const SETUP_PROVIDERS = [provideShellSetup({ backend: () => new TauriSetupBackend(ipc) })];
 * // the main window: provideShellSetup({ backend, main: true, ready: windowReady })  (opens the window on a first run)
 * ```
 */
